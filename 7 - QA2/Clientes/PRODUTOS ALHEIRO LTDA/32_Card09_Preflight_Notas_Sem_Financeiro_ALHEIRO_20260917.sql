PROMPT === IDENTIDADE E QUANTIDADES DO BACKUP ===
SELECT SYS_CONTEXT('USERENV','SESSION_USER') AS SESSION_USER,
       SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AS CURRENT_SCHEMA,
       SYS_CONTEXT('USERENV','SERVICE_NAME') AS SERVICE_NAME,
       SYS_CONTEXT('USERENV','DB_NAME') AS DB_NAME
  FROM DUAL;

SELECT STATUS_PREFLIGHT, COUNT(*) AS QTD
  FROM BKP_RMD_ALH_DUP_20260917
 GROUP BY STATUS_PREFLIGHT
 ORDER BY STATUS_PREFLIGHT;

SELECT COUNT(*) AS LINHAS_BACKUP,
       COUNT(DISTINCT NUNOTA) AS NOTAS_BACKUP,
       SUM(CASE WHEN STATUS_PREFLIGHT='CANDIDATO_XML_VALIDO' THEN 1 ELSE 0 END) AS CANDIDATOS_XML_VALIDOS,
       SUM(CASE WHEN VDUP_XML IS NOT NULL THEN 1 ELSE 0 END) AS NOTAS_COM_VDUP,
       SUM(CASE WHEN DVENC_XML IS NOT NULL THEN 1 ELSE 0 END) AS NOTAS_COM_DVENC
  FROM BKP_RMD_ALH_DUP_20260917;

