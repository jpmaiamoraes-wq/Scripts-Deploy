DECLARE
  v_owner VARCHAR2(128):=SYS_CONTEXT('USERENV','CURRENT_SCHEMA');
  PROCEDURE cria_se_ausente(p_nome VARCHAR2,p_ddl VARCHAR2) IS
    v_existe NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_existe FROM ALL_TABLES
     WHERE OWNER=v_owner AND TABLE_NAME=p_nome;
    IF v_existe=0 THEN EXECUTE IMMEDIATE p_ddl; END IF;
  END;
BEGIN
  cria_se_ausente('RMD_ALH_2930_MAP',
    'CREATE TABLE RMD_ALH_2930_MAP (ID_EXECUCAO VARCHAR2(40) NOT NULL,TIPO VARCHAR2(4) NOT NULL,COD_OBSOLETO NUMBER NOT NULL,COD_MANTIDO NUMBER NOT NULL,CHAVE_NORM VARCHAR2(4000),DH_LOG TIMESTAMP NOT NULL)');
  cria_se_ausente('RMD_ALH_2930_BAI_BKP',
    'CREATE TABLE RMD_ALH_2930_BAI_BKP AS SELECT CAST(NULL AS VARCHAR2(40)) ID_EXECUCAO,CAST(NULL AS TIMESTAMP) DH_EXECUCAO,CAST(NULL AS VARCHAR2(128)) USUARIO_EXECUCAO,B.* FROM TSIBAI B WHERE 1=0');
  cria_se_ausente('RMD_ALH_2930_END_BKP',
    'CREATE TABLE RMD_ALH_2930_END_BKP AS SELECT CAST(NULL AS VARCHAR2(40)) ID_EXECUCAO,CAST(NULL AS TIMESTAMP) DH_EXECUCAO,CAST(NULL AS VARCHAR2(128)) USUARIO_EXECUCAO,E.* FROM TSIEND E WHERE 1=0');
  cria_se_ausente('RMD_ALH_2930_DEP',
    'CREATE TABLE RMD_ALH_2930_DEP (ID_EXECUCAO VARCHAR2(40) NOT NULL,TABLE_NAME VARCHAR2(128) NOT NULL,COLUMN_NAME VARCHAR2(128) NOT NULL,RID VARCHAR2(30) NOT NULL,OLD_VALUE NUMBER,NEW_VALUE NUMBER,DH_LOG TIMESTAMP NOT NULL)');
  cria_se_ausente('RMD_ALH_2930_EXC',
    'CREATE TABLE RMD_ALH_2930_EXC (ID_EXECUCAO VARCHAR2(40) NOT NULL,TABLE_NAME VARCHAR2(128) NOT NULL,COLUMN_NAME VARCHAR2(128) NOT NULL,MENSAGEM VARCHAR2(1000) NOT NULL,DH_LOG TIMESTAMP NOT NULL)');
  DBMS_OUTPUT.PUT_LINE('TABELAS_AUDITORIA_29_30=CRIADAS_OU_EXISTENTES');
END;
