PROMPT === CONTROLES DE UNICIDADE E SEGURANCA ===
SELECT COUNT(*) AS LINHAS_MAPA,
       COUNT(DISTINCT NUNOTA) AS NOTAS_MAPA,
       SUM(CASE WHEN STATUS_MAPA='APTO_PARA_INSERCAO_CONTROLADA' THEN 1 ELSE 0 END) AS LINHAS_APTAS,
       COUNT(DISTINCT CASE WHEN STATUS_MAPA='APTO_PARA_INSERCAO_CONTROLADA' THEN NUNOTA END) AS NOTAS_APTAS,
       SUM(QTD_TGFFIN_ATUAL) AS TGFFIN_EXISTENTE_NO_MAPA,
       MIN(QTD_TGFNUM_TGFFIN) AS TGFNUM_LINHAS,
       MIN(ULTCOD_TGFNUM_ATUAL) AS ULTCOD_TGFNUM
  FROM BKP_RMD_ALH_DUP_PPG_20260917;

SELECT NUNOTA, COUNT(*) AS LINHAS_APTAS_POR_NOTA
  FROM BKP_RMD_ALH_DUP_PPG_20260917
 WHERE STATUS_MAPA='APTO_PARA_INSERCAO_CONTROLADA'
 GROUP BY NUNOTA
HAVING COUNT(*)<>1
 ORDER BY NUNOTA;

