  FROM BKP_VDA_FDUP_20260918
 WHERE VDUP_XML IS NOT NULL
   AND NOT REGEXP_LIKE(DVENC_XML,'^[0-9]{4}-[0-9]{2}-[0-9]{2}$');

SELECT CODTIPOPER,DESCROPER,COUNT(*) AS CANDIDATOS
  FROM BKP_VDA_FDUP_20260918
 WHERE VDUP_XML IS NOT NULL
   AND REGEXP_LIKE(DVENC_XML,'^[0-9]{4}-[0-9]{2}-[0-9]{2}$')
 GROUP BY CODTIPOPER,DESCROPER
 ORDER BY CODTIPOPER;

