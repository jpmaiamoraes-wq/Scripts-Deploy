DECLARE
  v_owner VARCHAR2(128):=SYS_CONTEXT('USERENV','CURRENT_SCHEMA');
  v_n NUMBER;
  PROCEDURE cria(p_nome VARCHAR2,p_ddl VARCHAR2) IS
  BEGIN
    SELECT COUNT(*) INTO v_n FROM ALL_TABLES WHERE OWNER=v_owner AND TABLE_NAME=p_nome;
    IF v_n=0 THEN EXECUTE IMMEDIATE p_ddl; END IF;
  END;
BEGIN
  cria('RMD_VDA_2930_MAP','CREATE TABLE RMD_VDA_2930_MAP (ID_EXECUCAO VARCHAR2(40) NOT NULL,TIPO VARCHAR2(4) NOT NULL,COD_OBSOLETO NUMBER NOT NULL,COD_MANTIDO NUMBER NOT NULL,CHAVE_NORM VARCHAR2(4000),DH_LOG TIMESTAMP NOT NULL)');
  cria('RMD_VDA_2930_BAI_BKP','CREATE TABLE RMD_VDA_2930_BAI_BKP AS SELECT CAST(NULL AS VARCHAR2(40)) ID_EXECUCAO,CAST(NULL AS TIMESTAMP) DH_EXECUCAO,CAST(NULL AS VARCHAR2(128)) USUARIO_EXECUCAO,B.* FROM TSIBAI B WHERE 1=0');
