DECLARE
 v_s1 VARCHAR2(8);v_s2 VARCHAR2(8);v_total NUMBER:=0;v_descr NUMBER:=0;
 PROCEDURE restaura IS
 BEGIN
  IF v_s1='ENABLED' THEN EXECUTE IMMEDIATE 'ALTER TRIGGER TRG_INC_UPD_TGFITE ENABLE';END IF;
  IF v_s2='ENABLED' THEN EXECUTE IMMEDIATE 'ALTER TRIGGER TRG_UPT_TGFITE ENABLE';END IF;
 END;
 PROCEDURE salva(p_tab VARCHAR2,p_col VARCHAR2) IS v_sql CLOB;BEGIN
  v_sql:='INSERT INTO BKP_RMD_UNID_'||p_tab||' SELECT :1,SYSTIMESTAMP,SYS_CONTEXT(''USERENV'',''SESSION_USER''),ROWIDTOCHAR(T.ROWID),T.* FROM '||p_tab||' T WHERE EXISTS(SELECT 1 FROM RMD_MAP_UNIDADES M WHERE M.FROM_CODE=T.'||p_col||')';
  EXECUTE IMMEDIATE v_sql USING 'RMD_UNID_20260909091500000';v_total:=v_total+SQL%ROWCOUNT;
 END;
BEGIN
 SELECT STATUS INTO v_s1 FROM ALL_TRIGGERS WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND TRIGGER_NAME='TRG_INC_UPD_TGFITE';
 SELECT STATUS INTO v_s2 FROM ALL_TRIGGERS WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND TRIGGER_NAME='TRG_UPT_TGFITE';
 salva('TGFPRO','CODVOL');salva('TGFITE','CODVOL');salva('TGFPAP','UNIDADEPARC');
 salva('TGFCOI2','CODVOL');salva('TGFGIR1','CODVOL');salva('TGFVOA','CODVOL');salva('TGFVOL','CODVOL');
 EXECUTE IMMEDIATE q'[INSERT INTO BKP_RMD_UNID_TGFVOL
 SELECT 'RMD_UNID_20260909091500000',SYSTIMESTAMP,SYS_CONTEXT('USERENV','SESSION_USER'),ROWIDTOCHAR(T.ROWID),T.*
 FROM TGFVOL T
 WHERE T.DESCRVOL<>UPPER(T.DESCRVOL)
   AND NOT EXISTS(SELECT 1 FROM RMD_MAP_UNIDADES M WHERE M.FROM_CODE=T.CODVOL)]';
 v_total:=v_total+SQL%ROWCOUNT;
 IF v_s1='ENABLED' THEN
  INSERT INTO RMD_CONTROLE_OBJETOS(ID_MASTER,ID_EXECUCAO,DH_REGISTRO,USUARIO_EXECUCAO,OBJECT_TYPE,OBJECT_NAME,STATUS_ANTES)
  VALUES('RMD_MASTER_20260909','RMD_UNID_20260909091500000',SYSTIMESTAMP,SYS_CONTEXT('USERENV','SESSION_USER'),'TRIGGER','TRG_INC_UPD_TGFITE',v_s1);
  EXECUTE IMMEDIATE 'ALTER TRIGGER TRG_INC_UPD_TGFITE DISABLE';
 END IF;
 IF v_s2='ENABLED' THEN
  INSERT INTO RMD_CONTROLE_OBJETOS(ID_MASTER,ID_EXECUCAO,DH_REGISTRO,USUARIO_EXECUCAO,OBJECT_TYPE,OBJECT_NAME,STATUS_ANTES)
  VALUES('RMD_MASTER_20260909','RMD_UNID_20260909091500000',SYSTIMESTAMP,SYS_CONTEXT('USERENV','SESSION_USER'),'TRIGGER','TRG_UPT_TGFITE',v_s2);
  EXECUTE IMMEDIATE 'ALTER TRIGGER TRG_UPT_TGFITE DISABLE';
 END IF;
 UPDATE TGFPRO P SET CODVOL=(SELECT TO_CODE FROM RMD_MAP_UNIDADES WHERE FROM_CODE=P.CODVOL) WHERE EXISTS(SELECT 1 FROM RMD_MAP_UNIDADES WHERE FROM_CODE=P.CODVOL);
 UPDATE TGFITE I SET CODVOL=(SELECT TO_CODE FROM RMD_MAP_UNIDADES WHERE FROM_CODE=I.CODVOL) WHERE EXISTS(SELECT 1 FROM RMD_MAP_UNIDADES WHERE FROM_CODE=I.CODVOL);
 UPDATE TGFPAP P SET UNIDADEPARC=(SELECT TO_CODE FROM RMD_MAP_UNIDADES WHERE FROM_CODE=P.UNIDADEPARC) WHERE EXISTS(SELECT 1 FROM RMD_MAP_UNIDADES WHERE FROM_CODE=P.UNIDADEPARC);
 UPDATE TGFCOI2 C SET CODVOL=(SELECT TO_CODE FROM RMD_MAP_UNIDADES WHERE FROM_CODE=C.CODVOL) WHERE EXISTS(SELECT 1 FROM RMD_MAP_UNIDADES WHERE FROM_CODE=C.CODVOL);
 UPDATE TGFGIR1 G SET CODVOL=(SELECT TO_CODE FROM RMD_MAP_UNIDADES WHERE FROM_CODE=G.CODVOL) WHERE EXISTS(SELECT 1 FROM RMD_MAP_UNIDADES WHERE FROM_CODE=G.CODVOL);
 DELETE FROM TGFVOA WHERE CODVOL IN(SELECT FROM_CODE FROM RMD_MAP_UNIDADES);
 DELETE FROM TGFVOL WHERE CODVOL IN(SELECT FROM_CODE FROM RMD_MAP_UNIDADES);
 UPDATE TGFVOL SET DESCRVOL=UPPER(DESCRVOL) WHERE DESCRVOL<>UPPER(DESCRVOL);
 v_descr:=SQL%ROWCOUNT;
 restaura;
 UPDATE RMD_CONTROLE_OBJETOS SET STATUS_DEPOIS='ENABLED',DH_REABILITACAO=SYSTIMESTAMP
  WHERE ID_MASTER='RMD_MASTER_20260909' AND ID_EXECUCAO='RMD_UNID_20260909091500000'
    AND OBJECT_TYPE='TRIGGER' AND STATUS_ANTES='ENABLED';
 COMMIT;
 DBMS_OUTPUT.PUT_LINE('ID_EXECUCAO='||'RMD_UNID_20260909091500000');DBMS_OUTPUT.PUT_LINE('REGISTROS_BACKUP='||v_total);
 DBMS_OUTPUT.PUT_LINE('DESCRICOES_TGFVOL_MAIUSCULAS='||v_descr);
EXCEPTION WHEN OTHERS THEN
 BEGIN restaura;EXCEPTION WHEN OTHERS THEN NULL;END;
 ROLLBACK;RAISE;
END;
