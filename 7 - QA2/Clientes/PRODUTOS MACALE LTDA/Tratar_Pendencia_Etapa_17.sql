DECLARE
 PROCEDURE cria(p_tab VARCHAR2) IS v NUMBER;BEGIN
  SELECT COUNT(*) INTO v FROM ALL_TABLES WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND TABLE_NAME='BKP_RMD_UNID_'||p_tab;
  IF v=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE BKP_RMD_UNID_'||p_tab||' AS SELECT CAST(NULL AS VARCHAR2(30)) ID_EXECUCAO,CAST(NULL AS TIMESTAMP) DH_EXECUCAO,CAST(NULL AS VARCHAR2(128)) USUARIO_EXECUCAO,CAST(NULL AS VARCHAR2(30)) ROWID_ORIGINAL,T.* FROM '||p_tab||' T WHERE 1=0';END IF;
 END;
BEGIN
 FOR T IN(SELECT 'TGFPRO' N FROM DUAL UNION ALL SELECT 'TGFITE' FROM DUAL UNION ALL SELECT 'TGFPAP' FROM DUAL UNION ALL SELECT 'TGFCOI2' FROM DUAL UNION ALL SELECT 'TGFGIR1' FROM DUAL UNION ALL SELECT 'TGFVOA' FROM DUAL UNION ALL SELECT 'TGFVOL' FROM DUAL)LOOP cria(T.N);END LOOP;
END;
