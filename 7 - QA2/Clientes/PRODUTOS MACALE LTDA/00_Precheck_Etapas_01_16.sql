SELECT N.NOME,N.TIPO_ESPERADO,NVL(O.OBJECT_TYPE,'AUSENTE') TIPO_ENCONTRADO,NVL(O.STATUS,'AUSENTE') STATUS
FROM (
 SELECT 'TSIPAR' NOME,'TABLE' TIPO_ESPERADO FROM DUAL UNION ALL SELECT 'TGFEMP','TABLE' FROM DUAL
 UNION ALL SELECT 'TGFTOP','TABLE' FROM DUAL UNION ALL SELECT 'TGFPRO','TABLE' FROM DUAL
 UNION ALL SELECT 'TGFTPV','TABLE' FROM DUAL UNION ALL SELECT 'TGFCAB','TABLE' FROM DUAL
 UNION ALL SELECT 'TGFITE','TABLE' FROM DUAL UNION ALL SELECT 'TTKNOT','TABLE' FROM DUAL
 UNION ALL SELECT 'TTKINDAGT','TABLE' FROM DUAL UNION ALL SELECT 'TSIIMP','TABLE' FROM DUAL
 UNION ALL SELECT 'TSICFG','TABLE' FROM DUAL UNION ALL SELECT 'AD_SEGMENTACAOEMPRESAS','TABLE' FROM DUAL
 UNION ALL SELECT 'TRG_UPT_TGFITE','TRIGGER' FROM DUAL
) N LEFT JOIN ALL_OBJECTS O
 ON O.OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND O.OBJECT_NAME=N.NOME AND O.OBJECT_TYPE=N.TIPO_ESPERADO
ORDER BY N.NOME;

