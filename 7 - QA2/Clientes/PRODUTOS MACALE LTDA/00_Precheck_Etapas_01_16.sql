UNION ALL SELECT '05_GIRO_PRODUTOS',COUNT(*) FROM TGFPRO WHERE USOPROD IN ('V','R') AND NVL(CALCULOGIRO,'?')<>'G'
UNION ALL SELECT '06_PARCELAS_TPV',COUNT(*) FROM TGFTPV WHERE NVL(NROPARCELAS,-1)<>0
UNION ALL SELECT '07_DTMOV_A_PREENCHER',COUNT(*) FROM TGFCAB WHERE DTMOV IS NULL AND TIPMOV<>'Z'
UNION ALL SELECT '08_PROTOCOLOS_LEGADOS',COUNT(*) FROM TGFCAB C WHERE EXISTS (SELECT 1 FROM TTKNOT N WHERE N.NUNOTA=C.NUNOTA)
 AND ((C.NUMPROTOC IS NULL AND EXISTS (SELECT 1 FROM TGFTOP T WHERE T.CODTIPOPER=C.CODTIPOPER AND T.DHALTER=C.DHTIPOPER AND T.CODMODDOC=55))
   OR (C.NUMPROTOCCTE IS NULL AND EXISTS (SELECT 1 FROM TGFTOP T WHERE T.CODTIPOPER=C.CODTIPOPER AND T.DHALTER=C.DHTIPOPER AND T.CODMODDOC=57)))
UNION ALL SELECT '09_ITENS_LEGADOS',COUNT(*) FROM TGFITE I WHERE NVL(STATUSNOTA,'?')<>'L' AND EXISTS (SELECT 1 FROM TTKNOT N WHERE N.NUNOTA=I.NUNOTA)
UNION ALL SELECT '10_ICMS_GERENCIAL',COUNT(*) FROM TGFPRO WHERE USOPROD IN ('V','R') AND NVL(ICMSGERENCIA,'?')<>'S'
UNION ALL SELECT '11_RUPTURA_PRODUTOS',COUNT(*) FROM TGFPRO WHERE USOPROD IN ('V','R') AND NVL(CALRUPTURAESTOQUE,'N')<>'S'
