DECLARE
  v_tabela NUMBER;
  v_qtd NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_tabela FROM ALL_TABLES
   WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND TABLE_NAME='AD_SEGMENTACAOEMPRESAS';
  IF v_tabela=0 THEN
    DBMS_OUTPUT.PUT_LINE('12_EMPRESAS_RUPTURA=NAO_AVALIADO_TABELA_AUSENTE');
  ELSE
    EXECUTE IMMEDIATE q'[SELECT COUNT(*) FROM TGFEMP E
      WHERE NVL(E.RUPTURAEST,'N')<>'S' AND EXISTS (
        SELECT 1 FROM AD_SEGMENTACAOEMPRESAS S JOIN TSIEMP T ON T.CGC=S.CGC
         WHERE S.SEGMENTACAO<>'S' AND T.CODEMP=E.CODEMP)]' INTO v_qtd;
    DBMS_OUTPUT.PUT_LINE('12_EMPRESAS_RUPTURA='||v_qtd);
  END IF;
END;
