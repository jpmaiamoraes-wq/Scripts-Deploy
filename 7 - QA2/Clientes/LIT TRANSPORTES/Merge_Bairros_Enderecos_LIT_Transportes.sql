DECLARE
  v_par_bai NUMBER;
  v_par_end NUMBER;
  v_cep_bai NUMBER;
  v_cep_end NUMBER;
  v_bkp_bai NUMBER;
  v_bkp_end NUMBER;
  v_faltantes NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_par_bai FROM TGFPAR
   WHERE CODBAI IN (SELECT COD_OBSOLETO FROM BKP_MBE_MAP_BAI WHERE ID_EXECUCAO='LITTRANSPORTES_20260901_080644');
  SELECT COUNT(*) INTO v_par_end FROM TGFPAR
   WHERE CODEND IN (SELECT COD_OBSOLETO FROM BKP_MBE_MAP_END WHERE ID_EXECUCAO='LITTRANSPORTES_20260901_080644');
  SELECT COUNT(*) INTO v_cep_bai FROM TSICEP
   WHERE CODBAI IN (SELECT COD_OBSOLETO FROM BKP_MBE_MAP_BAI WHERE ID_EXECUCAO='LITTRANSPORTES_20260901_080644');
  SELECT COUNT(*) INTO v_cep_end FROM TSICEP
   WHERE CODEND IN (SELECT COD_OBSOLETO FROM BKP_MBE_MAP_END WHERE ID_EXECUCAO='LITTRANSPORTES_20260901_080644');

  IF v_par_bai <> 3 OR v_par_end <> 13 OR v_cep_bai <> 11456 OR v_cep_end <> 49746 THEN
    RAISE_APPLICATION_ERROR(-20013,
      'Referencias divergiram: TGFPAR.BAI=' || v_par_bai || ', TGFPAR.END=' || v_par_end ||
      ', TSICEP.BAI=' || v_cep_bai || ', TSICEP.END=' || v_cep_end);
  END IF;

  SELECT COUNT(*) INTO v_bkp_bai FROM BKP_MBE_TSIBAI
   WHERE ID_EXECUCAO='LITTRANSPORTES_20260901_080644';
  SELECT COUNT(*) INTO v_bkp_end FROM BKP_MBE_TSIEND
   WHERE ID_EXECUCAO='LITTRANSPORTES_20260901_080644';
  IF v_bkp_bai <> 852 OR v_bkp_end <> 14230 THEN
    RAISE_APPLICATION_ERROR(-20014,
      'Backups dos cadastros divergiram: TSIBAI=' || v_bkp_bai || ', TSIEND=' || v_bkp_end);
  END IF;

  SELECT
    (SELECT COUNT(*) FROM TGFPAR p
      WHERE (p.CODBAI IN (SELECT COD_OBSOLETO FROM BKP_MBE_MAP_BAI WHERE ID_EXECUCAO='LITTRANSPORTES_20260901_080644')
         OR  p.CODEND IN (SELECT COD_OBSOLETO FROM BKP_MBE_MAP_END WHERE ID_EXECUCAO='LITTRANSPORTES_20260901_080644'))
        AND NOT EXISTS (SELECT 1 FROM BKP_MBE_TGFPAR b
                         WHERE b.ID_EXECUCAO='LITTRANSPORTES_20260901_080644'
                           AND CHARTOROWID(b.ROWID_ORIGINAL)=p.ROWID))
    +
    (SELECT COUNT(*) FROM TSICEP c
      WHERE (c.CODBAI IN (SELECT COD_OBSOLETO FROM BKP_MBE_MAP_BAI WHERE ID_EXECUCAO='LITTRANSPORTES_20260901_080644')
         OR  c.CODEND IN (SELECT COD_OBSOLETO FROM BKP_MBE_MAP_END WHERE ID_EXECUCAO='LITTRANSPORTES_20260901_080644'))
        AND NOT EXISTS (SELECT 1 FROM BKP_MBE_TSICEP b
                         WHERE b.ID_EXECUCAO='LITTRANSPORTES_20260901_080644'
                           AND CHARTOROWID(b.ROWID_ORIGINAL)=c.ROWID))
    INTO v_faltantes FROM DUAL;
  IF v_faltantes <> 0 THEN
    RAISE_APPLICATION_ERROR(-20015, 'Existem linhas dependentes sem backup: ' || v_faltantes);
  END IF;
  DBMS_OUTPUT.PUT_LINE('OK: referencias e backups conferidos antes do merge.');
END;
