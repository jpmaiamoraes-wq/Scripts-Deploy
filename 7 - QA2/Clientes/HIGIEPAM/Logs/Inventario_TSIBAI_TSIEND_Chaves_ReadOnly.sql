SELECT C.OWNER AS CONSTRAINT_OWNER,
       C.CONSTRAINT_NAME,
       C.CONSTRAINT_TYPE,
       C.TABLE_NAME AS CHILD_TABLE,
       CC.POSITION AS CHILD_POSITION,
       CC.COLUMN_NAME AS CHILD_COLUMN,
       C.R_OWNER AS REFERENCED_OWNER,
       C.R_CONSTRAINT_NAME,
       RC.CONSTRAINT_TYPE AS REFERENCED_CONSTRAINT_TYPE,
       RC.TABLE_NAME AS REFERENCED_TABLE,
       RCC.POSITION AS REFERENCED_POSITION,
       RCC.COLUMN_NAME AS REFERENCED_COLUMN,
       C.STATUS,
       C.DEFERRABLE,
       C.DEFERRED
  FROM ALL_CONSTRAINTS C
  JOIN ALL_CONS_COLUMNS CC
    ON CC.OWNER = C.OWNER
   AND CC.CONSTRAINT_NAME = C.CONSTRAINT_NAME
  LEFT JOIN ALL_CONSTRAINTS RC
    ON RC.OWNER = C.R_OWNER
   AND RC.CONSTRAINT_NAME = C.R_CONSTRAINT_NAME
  LEFT JOIN ALL_CONS_COLUMNS RCC
    ON RCC.OWNER = RC.OWNER
   AND RCC.CONSTRAINT_NAME = RC.CONSTRAINT_NAME
   AND RCC.POSITION = CC.POSITION
 WHERE C.OWNER = SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
   AND (C.TABLE_NAME IN ('TSIBAI','TSIEND') OR RC.TABLE_NAME IN ('TSIBAI','TSIEND'))
 ORDER BY C.TABLE_NAME, C.CONSTRAINT_NAME, CC.POSITION
