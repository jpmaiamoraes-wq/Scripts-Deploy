SELECT 'TSIBAI' AS TABELA,
       ROWIDTOCHAR(ROWID) AS RID,
       CODBAI AS CODIGO,
       CODREG AS CONTEXTO,
       NOMEBAI AS NOME
  FROM TSIBAI
 WHERE ROWIDTOCHAR(ROWID) = 'AAAzpyAARAAAmYJABw'
UNION ALL
SELECT 'TSIEND' AS TABELA,
       ROWIDTOCHAR(ROWID) AS RID,
       CODEND AS CODIGO,
       NULL AS CONTEXTO,
       NOMEEND AS NOME
  FROM TSIEND
 WHERE ROWIDTOCHAR(ROWID) = 'AAAzpyAARAAAmYJABw'
UNION ALL
SELECT 'MAP_BAI_DUP_KEPT' AS TABELA,
       NULL AS RID,
       COD_MANTIDO AS CODIGO,
       NULL AS CONTEXTO,
       CHAVE_NORM AS NOME
  FROM RMD_HIGIEPAM_2930_MAP
 WHERE ID_EXECUCAO='RMD_HIGIEPAM_2930_MERGE_20260922082832'
   AND TIPO='BAI'
 GROUP BY COD_MANTIDO,CHAVE_NORM
HAVING COUNT(*)>1
UNION ALL
SELECT 'MAP_END_DUP_KEPT' AS TABELA,
       NULL AS RID,
       COD_MANTIDO AS CODIGO,
       NULL AS CONTEXTO,
       CHAVE_NORM AS NOME
  FROM RMD_HIGIEPAM_2930_MAP
 WHERE ID_EXECUCAO='RMD_HIGIEPAM_2930_MERGE_20260922082832'
   AND TIPO='END'
 GROUP BY COD_MANTIDO,CHAVE_NORM
HAVING COUNT(*)>1
;
