WITH B AS (
       SELECT REGEXP_REPLACE(TRIM(TRANSLATE(UPPER(NOMEBAI),
         'ÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇáàâãäéèêëíìîïóòôõöúùûüçÃãÕõÂâÊêÎîÔôÛû',
         'AAAAAEEEEIIIIOOOOOUUUUCAAAAAEEEEIIIIOOOOOUUUUCAAAOOAAEIIOOUU')),' {2,}',' ') NORM
         FROM TSIBAI
     ), BD AS (
       SELECT NORM FROM B GROUP BY NORM HAVING COUNT(*)>1
     ), E AS (
       SELECT TIPO,
              REGEXP_REPLACE(TRIM(TRANSLATE(UPPER(NOMEEND),
                'ÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇáàâãäéèêëíìîïóòôõöúùûüçÃãÕõÂâÊêÎîÔôÛû',
                'AAAAAEEEEIIIIOOOOOUUUUCAAAAAEEEEIIIIOOOOOUUUUCAAAOOAAEIIOOUU')),' {2,}',' ') NORM
         FROM TSIEND
     ), ED AS (
       SELECT TIPO,NORM FROM E GROUP BY TIPO,NORM HAVING COUNT(*)>1
     )
SELECT 'BAIRROS_OBSOLETOS_REMANESCENTES' AS METRICA,
       COUNT(*) AS QTD
  FROM TSIBAI b
 WHERE EXISTS (SELECT 1 FROM RMD_HIGIEPAM_2930_MAP m
                WHERE m.ID_EXECUCAO='RMD_HIGIEPAM_2930_MERGE_20260922082832'
                  AND m.TIPO='BAI' AND m.COD_OBSOLETO=b.CODBAI)
UNION ALL
SELECT 'ENDERECOS_OBSOLETOS_REMANESCENTES' AS METRICA,
       COUNT(*) AS QTD
  FROM TSIEND e
 WHERE EXISTS (SELECT 1 FROM RMD_HIGIEPAM_2930_MAP m
                WHERE m.ID_EXECUCAO='RMD_HIGIEPAM_2930_MERGE_20260922082832'
                  AND m.TIPO='END' AND m.COD_OBSOLETO=e.CODEND)
UNION ALL
SELECT 'BAIRROS_NORM_DUPLICADOS' AS METRICA,
       COUNT(*) AS QTD
  FROM BD
UNION ALL
SELECT 'ENDERECOS_NORM_DUPLICADOS' AS METRICA,
       COUNT(*) AS QTD
  FROM ED
UNION ALL
SELECT 'BACKUP_EXCLUSAO_TSIBAI' AS METRICA,
       COUNT(*) AS QTD
  FROM RMD_HIGIEPAM_2930_X_BAI
 WHERE ID_EXECUCAO='RMD_HIGIEPAM_2930_EXCL_20260922084148'
UNION ALL
SELECT 'BACKUP_EXCLUSAO_TSIEND' AS METRICA,
       COUNT(*) AS QTD
  FROM RMD_HIGIEPAM_2930_X_END
 WHERE ID_EXECUCAO='RMD_HIGIEPAM_2930_EXCL_20260922084148'
UNION ALL
SELECT 'EXCECOES_FASE_EXCLUSAO' AS METRICA,
       COUNT(*) AS QTD
  FROM RMD_HIGIEPAM_2930_EXC
 WHERE ID_EXECUCAO='RMD_HIGIEPAM_2930_EXCL_20260922084148'
;
