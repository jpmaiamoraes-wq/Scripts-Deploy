SELECT 'SESSION_PRIVILEGE' AS ITEM,
       PRIVILEGE AS VALOR,
       CAST(NULL AS VARCHAR2(128)) AS DETALHE
  FROM SESSION_PRIVS
UNION ALL
SELECT 'TABLESPACE_QUOTA' AS ITEM,
       TABLESPACE_NAME AS VALOR,
       TO_CHAR(MAX_BYTES) AS DETALHE
  FROM USER_TS_QUOTAS
UNION ALL
SELECT 'USER_TABLESPACE' AS ITEM,
       DEFAULT_TABLESPACE AS VALOR,
       TEMPORARY_TABLESPACE AS DETALHE
  FROM USER_USERS
 ORDER BY ITEM, VALOR
