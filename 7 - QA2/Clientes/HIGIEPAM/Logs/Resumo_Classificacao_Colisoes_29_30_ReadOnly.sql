WITH B AS (
       SELECT NORM,
              COUNT(*) AS QTD_REGISTROS,
              COUNT(DISTINCT CODREG) AS QTD_CODREG
         FROM (
               SELECT CODREG,
                      REGEXP_REPLACE(TRIM(TRANSLATE(UPPER(NOMEBAI),
                        'ÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇáàâãäéèêëíìîïóòôõöúùüçÃãÕõÂâÊêÎîÔôÛû',
                        'AAAAAEEEEIIIIOOOOOUUUUCAAAAAEEEEIIIIOOOOOUUUUCAAAOOAAEIIOOUU')),
                        ' {2,}',' ') AS NORM
                 FROM TSIBAI
              )
        GROUP BY NORM
       HAVING COUNT(*) > 1
     ), E AS (
       SELECT TIPO,
              NORM,
              COUNT(*) AS QTD_REGISTROS,
              COUNT(DISTINCT NVL(CODLOGRADOURO,'<NULL>')) AS QTD_CODLOGRADOURO
         FROM (
               SELECT TIPO,
                      CODLOGRADOURO,
                      REGEXP_REPLACE(TRIM(TRANSLATE(UPPER(NOMEEND),
                        'ÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇáàâãäéèêëíìîïóòôõöúùüçÃãÕõÂâÊêÎîÔôÛû',
                        'AAAAAEEEEIIIIOOOOOUUUUCAAAAAEEEEIIIIOOOOOUUUUCAAAOOAAEIIOOUU')),
                        ' {2,}',' ') AS NORM
                 FROM TSIEND
              )
        GROUP BY TIPO, NORM
       HAVING COUNT(*) > 1
     )
SELECT 'TSIBAI' AS ENTIDADE,
       COUNT(*) AS QTD_GRUPOS,
       SUM(CASE WHEN QTD_CODREG = 1 THEN 1 ELSE 0 END) AS GRUPOS_MESMO_CODREG,
       SUM(CASE WHEN QTD_CODREG > 1 THEN 1 ELSE 0 END) AS GRUPOS_CODREG_DIVERGENTE,
       SUM(QTD_REGISTROS) AS QTD_REGISTROS_COLISAO,
       CAST(NULL AS NUMBER) AS GRUPOS_MESMO_CODLOGRADOURO,
       CAST(NULL AS NUMBER) AS GRUPOS_CODLOGRADOURO_DIVERGENTE
  FROM B
UNION ALL
SELECT 'TSIEND' AS ENTIDADE,
       COUNT(*) AS QTD_GRUPOS,
       CAST(NULL AS NUMBER) AS GRUPOS_MESMO_CODREG,
       CAST(NULL AS NUMBER) AS GRUPOS_CODREG_DIVERGENTE,
       SUM(QTD_REGISTROS) AS QTD_REGISTROS_COLISAO,
       SUM(CASE WHEN QTD_CODLOGRADOURO = 1 THEN 1 ELSE 0 END) AS GRUPOS_MESMO_CODLOGRADOURO,
       SUM(CASE WHEN QTD_CODLOGRADOURO > 1 THEN 1 ELSE 0 END) AS GRUPOS_CODLOGRADOURO_DIVERGENTE
  FROM E
