SELECT ITEM,
       VALOR,
       DETALHE,
       STATUS
  FROM (
        SELECT 'IDENTIDADE' AS ITEM,
               SYS_CONTEXT('USERENV', 'SESSION_USER') AS VALOR,
               SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS DETALHE,
               SYS_CONTEXT('USERENV', 'SERVICE_NAME') AS STATUS
          FROM DUAL
        UNION ALL
        SELECT 'BASE_EMPRESAS', TO_CHAR(COUNT(*)), NULL, 'BASE_INTEIRA'
          FROM TSIEMP
        UNION ALL
        SELECT 'ETAPA_18_TGFCGM', TO_CHAR(COUNT(*)), 'TOTAL', 'READ_ONLY'
          FROM TGFCGM
        UNION ALL
        SELECT 'ETAPA_18_TGFCMV', TO_CHAR(COUNT(*)), 'TOTAL', 'READ_ONLY'
          FROM TGFCMV
        UNION ALL
        SELECT 'ETAPA_19_TGFPAR', TO_CHAR(COUNT(*)), 'TOTAL', 'READ_ONLY'
          FROM TGFPAR
        UNION ALL
        SELECT 'ETAPA_20_TTKINDAGT', TO_CHAR(COUNT(*)), 'TOTAL', 'READ_ONLY'
          FROM TTKINDAGT
        UNION ALL
        SELECT 'ETAPA_20_TTKNOT', TO_CHAR(COUNT(*)), 'TOTAL', 'READ_ONLY'
          FROM TTKNOT
        UNION ALL
        SELECT 'ETAPA_20_TTKEVT', TO_CHAR(COUNT(*)), 'TOTAL', 'READ_ONLY'
          FROM TTKEVT
        UNION ALL
        SELECT 'ETAPA_21_ICMS_DIVERGENTES', TO_CHAR(COUNT(*)), 'CANDIDATOS', 'READ_ONLY'
          FROM TGFPAR
         WHERE (TIPPESSOA='J' AND IDENTINSCESTAD IS NOT NULL AND UPPER(TRIM(IDENTINSCESTAD))<>'ISENTO' AND NVL(CLASSIFICMS,'Z')<>'R')
            OR (TIPPESSOA='F' AND IDENTINSCESTAD IS NOT NULL AND UPPER(TRIM(IDENTINSCESTAD))<>'ISENTO' AND NVL(CLASSIFICMS,'Z')<>'P')
            OR (NVL(UPPER(TRIM(IDENTINSCESTAD)),'ISENTO')='ISENTO' AND NVL(CLASSIFICMS,'Z')<>'C')
        UNION ALL
        SELECT 'ETAPA_22_TGFPAR_CGC_CPF', TO_CHAR(COUNT(*)), 'COM_IDENTIFICADOR', 'READ_ONLY'
          FROM TGFPAR
         WHERE CGC_CPF IS NOT NULL
        UNION ALL
        SELECT 'ETAPA_23_CONTROLE_OBJETOS',
               CASE WHEN EXISTS (
                      SELECT 1
                        FROM ALL_TABLES
                       WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
                         AND TABLE_NAME='RMD_CONTROLE_OBJETOS'
                    ) THEN 'EXISTENTE' ELSE 'A_SER_CRIADA' END,
               'CONTROLE_DA_REVISAO',
               'READ_ONLY'
          FROM DUAL
        UNION ALL
        SELECT 'ETAPA_24_TGFPAR', TO_CHAR(COUNT(*)), 'TOTAL', 'READ_ONLY'
          FROM TGFPAR
        UNION ALL
        SELECT 'ETAPA_25_TGFPRO', TO_CHAR(COUNT(*)), 'TOTAL', 'READ_ONLY'
          FROM TGFPRO
        UNION ALL
        SELECT 'ETAPA_26_TGFTIT', TO_CHAR(COUNT(*)), 'TOTAL', 'READ_ONLY'
          FROM TGFTIT
        UNION ALL
        SELECT 'ETAPA_27_TSICID', TO_CHAR(COUNT(*)), 'TOTAL', 'READ_ONLY'
          FROM TSICID
        UNION ALL
        SELECT 'ETAPA_28_TGFTPV', TO_CHAR(COUNT(*)), 'TOTAL', 'READ_ONLY'
          FROM TGFTPV
        UNION ALL
        SELECT 'ETAPA_29_TSIBAI', TO_CHAR(COUNT(*)), 'TOTAL', 'READ_ONLY'
          FROM TSIBAI
        UNION ALL
        SELECT 'ETAPA_30_TSIEND', TO_CHAR(COUNT(*)), 'TOTAL', 'READ_ONLY'
          FROM TSIEND
        UNION ALL
        SELECT 'OBJETOS_INVALIDOS', TO_CHAR(COUNT(*)), 'ALL_OBJECTS', 'READ_ONLY'
          FROM ALL_OBJECTS
         WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND STATUS='INVALID'
        UNION ALL
        SELECT 'PRIV_RECOMPILACAO', TO_CHAR(COUNT(*)), 'SESSION_PRIVS', 'READ_ONLY'
          FROM SESSION_PRIVS
         WHERE PRIVILEGE LIKE '%ANY PROCEDURE'
        UNION ALL
        SELECT 'QUOTAS_TABLESPACES', TO_CHAR(COUNT(*)), 'USER_TS_QUOTAS', 'DIAGNOSTICO'
          FROM USER_TS_QUOTAS
        UNION ALL
        SELECT 'BACKUPS_RMD_EXISTENTES', TO_CHAR(COUNT(*)), 'ALL_TABLES', 'PERSISTENCIA'
          FROM ALL_TABLES
         WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
           AND (TABLE_NAME LIKE 'BKP_RMD_%' OR TABLE_NAME LIKE 'RMD_%')
       )
 ORDER BY ITEM
