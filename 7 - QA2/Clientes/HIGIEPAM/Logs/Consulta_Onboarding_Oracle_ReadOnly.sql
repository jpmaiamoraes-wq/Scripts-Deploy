SELECT 'EMPRESA' AS TIPO_REGISTRO,
       TO_CHAR(E.CODEMP) AS CODIGO,
       TRIM(E.RAZAOSOCIAL) AS NOME,
       REGEXP_REPLACE(TO_CHAR(E.CGC), '[^0-9]', '') AS IDENTIFICADOR,
       CAST(NULL AS VARCHAR2(320)) AS EMAIL,
       CAST(NULL AS NUMBER) AS CODGRUPO,
       CAST(NULL AS VARCHAR2(100)) AS CODEMP_USUARIO
  FROM TSIEMP E
UNION ALL
SELECT 'USUARIO' AS TIPO_REGISTRO,
       TO_CHAR(U.CODUSU) AS CODIGO,
       TRIM(U.NOMEUSU) AS NOME,
       CAST(NULL AS VARCHAR2(100)) AS IDENTIFICADOR,
       LOWER(TRIM(U.EMAIL)) AS EMAIL,
       U.CODGRUPO,
       TO_CHAR(U.CODEMP) AS CODEMP_USUARIO
  FROM TSIUSU U
 ORDER BY TIPO_REGISTRO, CODIGO
