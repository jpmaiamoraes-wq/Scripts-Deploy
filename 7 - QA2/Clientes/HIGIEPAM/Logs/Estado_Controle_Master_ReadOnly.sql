SELECT ID_MASTER,
       COUNT(*) AS QTD_REGISTROS,
       MIN(DH_REGISTRO) AS PRIMEIRO_REGISTRO,
       MAX(DH_REGISTRO) AS ULTIMO_REGISTRO,
       MAX(ID_EXECUCAO) KEEP (DENSE_RANK LAST ORDER BY DH_REGISTRO) AS ULTIMO_ID_EXECUCAO
  FROM RMD_CONTROLE_OBJETOS
 GROUP BY ID_MASTER
 ORDER BY PRIMEIRO_REGISTRO;
