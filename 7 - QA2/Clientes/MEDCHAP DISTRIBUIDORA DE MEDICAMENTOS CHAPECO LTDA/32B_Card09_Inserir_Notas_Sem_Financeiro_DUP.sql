    DBMS_OUTPUT.PUT_LINE('STATUS=SEM_PENDENTES_PARA_INSERCAO');
    RETURN;
  END IF;
  SELECT COUNT(*) INTO v_qtd
    FROM &TBL_PPG M
    JOIN TGFCAB C ON C.NUNOTA=M.NUNOTA
    LEFT JOIN TGFTPV V
      ON V.CODTIPVENDA=M.CODTIPVENDA
     AND V.DHALTER=C.DHTIPVENDA
   WHERE M.ID_EXECUCAO='&ID_EXECUCAO'
     AND M.STATUS_MAPA='APTO_PARA_VALIDACAO_FINAL'
     AND V.CODTIPVENDA IS NULL;
  IF v_qtd > 0 THEN
    RAISE_APPLICATION_ERROR(-20329,'Uma ou mais notas nao possuem a versao exata da TGFTPV usada no cabecalho.');
  END IF;
  SELECT COUNT(*) INTO v_qtd
    FROM &TBL_PPG
   WHERE ID_EXECUCAO='&ID_EXECUCAO'
     AND STATUS_MAPA='APTO_PARA_VALIDACAO_FINAL'
     AND NOT REGEXP_LIKE(TRIM(VDUP_XML),'^[0-9]+([.][0-9]+)?$');
  IF v_qtd > 0 THEN
    RAISE_APPLICATION_ERROR(-20330,'Existe vDup XML nao numerico no mapa.');
  END IF;
  SELECT COUNT(*) INTO v_qtd
    FROM &TBL_PPG M
   WHERE M.ID_EXECUCAO='&ID_EXECUCAO'
     AND M.STATUS_MAPA='APTO_PARA_VALIDACAO_FINAL'
     AND NOT EXISTS (SELECT 1 FROM TGFTIT T WHERE T.CODTIPTIT=M.CODTIPTITPAD);
  IF v_qtd > 0 THEN
    RAISE_APPLICATION_ERROR(-20331,'Existe CODTIPTITPAD sem correspondente na TGFTIT.');
  END IF;
  SELECT COUNT(*) INTO v_tgfnum_rows FROM TGFNUM WHERE ARQUIVO='TGFFIN';
  DBMS_OUTPUT.PUT_LINE('TGFNUM_TGFFIN_ROWS='||v_tgfnum_rows);
  IF v_tgfnum_rows <> 1 THEN
    FOR t IN (SELECT ARQUIVO, ULTCOD FROM TGFNUM WHERE ARQUIVO='TGFFIN' ORDER BY ULTCOD) LOOP
      DBMS_OUTPUT.PUT_LINE('TGFNUM_ROW ARQUIVO='||t.ARQUIVO||' ULTCOD='||t.ULTCOD);
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('DIAGNOSTICO_TGFNUM; nenhuma alteração realizada.');
    ROLLBACK;
    RETURN;
  END IF;
  IF v_confirm <> 'SIM' THEN
    DBMS_OUTPUT.PUT_LINE('STATUS=NAO_EXECUTADO; altere CONFIRMA_INSERCAO para SIM após revisar o mapa.');
    RETURN;
  END IF;
  DBMS_OUTPUT.PUT_LINE('ANTES_LOCK_TGFNUM');
  SELECT ULTCOD INTO v_ultcod FROM TGFNUM WHERE ARQUIVO='TGFFIN' FOR UPDATE WAIT 5;
  DBMS_OUTPUT.PUT_LINE('APOS_LOCK_TGFNUM ULTCOD='||v_ultcod);
  SELECT COUNT(*) INTO v_qtd FROM &TBL_INS WHERE ID_EXECUCAO='&ID_EXECUCAO';
  IF v_qtd > 0 THEN
    RAISE_APPLICATION_ERROR(-20327,'Ja existem inclusoes auditadas para este ID_EXECUCAO.');
  END IF;
