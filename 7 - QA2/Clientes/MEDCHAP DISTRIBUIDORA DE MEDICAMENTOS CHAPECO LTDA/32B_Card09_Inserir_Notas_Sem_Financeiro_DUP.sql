    v_nufin := v_ultcod + 1;
    DBMS_OUTPUT.PUT_LINE('PROCESSANDO NUNOTA='||r.NUNOTA||' NUFIN='||v_nufin||' VDUP='||r.VDUP_XML||' DVENC='||r.DVENC_XML||' NDUP='||NVL(r.NDUP_XML,'<NULL>'));
