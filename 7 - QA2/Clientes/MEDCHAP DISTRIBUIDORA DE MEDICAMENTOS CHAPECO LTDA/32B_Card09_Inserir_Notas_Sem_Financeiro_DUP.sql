-- Etapa 32B - Inclusao controlada de financeiros a partir do XML
--
-- Executa somente com CONFIRMA_INSERCAO = SIM.
-- Regras consolidadas: TIPRECDESP textual (I/R/D/P) e convertido para RECDESP numerico;
-- CODBCO nulo recebe 0 e TIPJURO usa 1 quando a TGFTPV retorna o marcador textual I.
-- O mapa 32A pode conter linhas inelegiveis; somente as linhas APTO_PARA_VALIDACAO_FINAL
-- entram no DML.
-- O INSERT reproduz os campos e padroes observados na rotina nativa REFAZER FINANCEIRO.

SET DEFINE ON

-- Parametros obrigatorios: devem ser os mesmos usados no script 32A.
-- Mantenha CONFIRMA_INSERCAO=NAO para o mapa/preflight; altere para SIM
-- somente depois da revisao final do mapa.
DEFINE ID_EXECUCAO = '&&CARD09_ID_EXECUCAO'
DEFINE TBL_BASE = '&&CARD09_TBL_BASE'
DEFINE TBL_PPG = '&&CARD09_TBL_PPG'
DEFINE TBL_INS = '&&CARD09_TBL_INS'
SET SERVEROUTPUT ON SIZE UNLIMITED
SET SQLBLANKLINES ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DEFINE CONFIRMA_INSERCAO = '&&CARD09_CONFIRMA_INSERCAO'

