  END IF;
  SELECT COUNT(*), COUNT(DISTINCT NUNOTA) INTO v_qtd, v_distinct FROM &TBL_PPG WHERE ID_EXECUCAO='&ID_EXECUCAO' AND STATUS_MAPA='APTO_PARA_VALIDACAO_FINAL';
  IF v_qtd = 0 OR v_qtd <> v_distinct THEN
    RAISE_APPLICATION_ERROR(-20324,'Mapa vazio ou com mais de uma linha por NUNOTA; revisar parcelas antes do INSERT.');
  END IF;
  SELECT COUNT(DISTINCT M.NUNOTA) INTO v_existentes
    FROM TGFFIN F
    JOIN &TBL_PPG M ON M.NUNOTA=F.NUNOTA AND M.ID_EXECUCAO='&ID_EXECUCAO' AND M.STATUS_MAPA='APTO_PARA_VALIDACAO_FINAL';
  SELECT COUNT(*) INTO v_pendentes
    FROM &TBL_PPG M
   WHERE M.ID_EXECUCAO='&ID_EXECUCAO'
     AND M.STATUS_MAPA='APTO_PARA_VALIDACAO_FINAL'
     AND NOT EXISTS (SELECT 1 FROM TGFFIN F WHERE F.NUNOTA=M.NUNOTA);
  DBMS_OUTPUT.PUT_LINE('JA_EXISTIAM_TGFFIN='||v_existentes);
  DBMS_OUTPUT.PUT_LINE('PENDENTES_PARA_INSERCAO='||v_pendentes);
