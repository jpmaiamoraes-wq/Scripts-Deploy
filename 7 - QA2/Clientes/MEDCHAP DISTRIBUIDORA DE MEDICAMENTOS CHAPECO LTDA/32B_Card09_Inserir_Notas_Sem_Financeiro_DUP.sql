    SELECT M.*, C.TIPMOV, V.TIPJURO
      FROM &TBL_PPG M
      JOIN TGFCAB C ON C.NUNOTA=M.NUNOTA
      LEFT JOIN TGFTPV V ON V.CODTIPVENDA=M.CODTIPVENDA AND V.DHALTER=C.DHTIPVENDA
     WHERE M.ID_EXECUCAO='&ID_EXECUCAO'
       AND M.STATUS_MAPA='APTO_PARA_VALIDACAO_FINAL'
       AND NOT EXISTS (SELECT 1 FROM TGFFIN F WHERE F.NUNOTA=M.NUNOTA)
     ORDER BY M.NUNOTA, M.SEQ_PPG
