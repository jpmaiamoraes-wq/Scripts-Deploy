DECLARE
  v_qtd NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_qtd FROM ALL_TABLES WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND TABLE_NAME='&TBL_INS';
  IF v_qtd=0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE &TBL_INS (ID_EXECUCAO VARCHAR2(40) NOT NULL, DH_EXECUCAO TIMESTAMP NOT NULL, NUNOTA NUMBER NOT NULL, NUFIN NUMBER NOT NULL, VLRDESDOB NUMBER, DTVENC DATE)]';
  END IF;
END;
