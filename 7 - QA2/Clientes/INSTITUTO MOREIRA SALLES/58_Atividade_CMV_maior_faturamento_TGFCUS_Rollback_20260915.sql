SELECT SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AS CURRENT_SCHEMA,
       SYS_CONTEXT('USERENV','SESSION_USER') AS SESSION_USER,
       SYS_CONTEXT('USERENV','SERVICE_NAME') AS SERVICE_NAME,
       SYSTIMESTAMP AS DH_ROLLBACK,
       'RMD_CMV_CUS_IMS_20260915_142359' AS ID_EXECUCAO,
       '&&CONFIRMA_ROLLBACK' AS CONFIRMACAO
  FROM DUAL;

SELECT OWNER,TRIGGER_NAME,TABLE_NAME,STATUS,TRIGGERING_EVENT,TRIGGER_TYPE
  FROM ALL_TRIGGERS
 WHERE OWNER='SANKHYA'
   AND TRIGGER_NAME='TRG_DLT_UPD_TGFCUS';

DECLARE
  v_confirm VARCHAR2(10):=UPPER(TRIM('&&CONFIRMA_ROLLBACK'));
  v_status VARCHAR2(20);
  v_backup NUMBER;
  v_duplicados NUMBER;
  v_antes NUMBER;
  v_excluidos NUMBER;
  v_inseridos NUMBER;
  v_depois NUMBER;
  v_cols VARCHAR2(32767);
  v_sql VARCHAR2(32767);
BEGIN
  SELECT COUNT(*) INTO v_backup FROM BKP_CMV_CUS_20260915_142359;
  IF v_backup=0 THEN
    RAISE_APPLICATION_ERROR(-20390,'Backup TGFCUS sem registros; rollback interrompido.');
  END IF;

  IF v_confirm<>'SIM' THEN
    DBMS_OUTPUT.PUT_LINE('STATUS=NAO_EXECUTADO; altere CONFIRMA_ROLLBACK para SIM apos revisar.');
    RETURN;
  END IF;

  SELECT STATUS INTO v_status
    FROM ALL_TRIGGERS
   WHERE OWNER='SANKHYA'
     AND TRIGGER_NAME='TRG_DLT_UPD_TGFCUS';
  IF v_status<>'DISABLED' THEN
    RAISE_APPLICATION_ERROR(-20391,
      'A trigger TRG_DLT_UPD_TGFCUS deve estar DISABLED durante o rollback. Status='||v_status);
  END IF;

  SELECT COUNT(*) INTO v_duplicados
    FROM (SELECT CODPROD,CODEMP,DTATUAL,CODLOCAL,CONTROLE,NUNOTA,SEQUENCIA,
                 COUNT(*) AS QTD
            FROM BKP_CMV_CUS_20260915_142359
           GROUP BY CODPROD,CODEMP,DTATUAL,CODLOCAL,CONTROLE,NUNOTA,SEQUENCIA
          HAVING COUNT(*)>1);
  IF v_duplicados>0 THEN
    RAISE_APPLICATION_ERROR(-20392,'Backup com PK duplicada; rollback interrompido.');
  END IF;

  SELECT COUNT(*) INTO v_antes
    FROM TGFCUS
   WHERE CODPROD IN (2237205918,2237205919,2237205920,2237205921,2237205922,
                     2237205923,2237205924,2237205925,2237205926,2237205927,
                     2237205928,2237205929,2237205930);

  SELECT LISTAGG('"'||COLUMN_NAME||'"',',') WITHIN GROUP(ORDER BY COLUMN_ID)
    INTO v_cols
    FROM ALL_TAB_COLUMNS
   WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
     AND TABLE_NAME='TGFCUS';

  IF v_cols IS NULL THEN
    RAISE_APPLICATION_ERROR(-20393,'Nao foi possivel obter as colunas de TGFCUS.');
  END IF;

  DELETE FROM TGFCUS
   WHERE CODPROD IN (2237205918,2237205919,2237205920,2237205921,2237205922,
                     2237205923,2237205924,2237205925,2237205926,2237205927,
                     2237205928,2237205929,2237205930);
  v_excluidos:=SQL%ROWCOUNT;

  v_sql:='INSERT INTO TGFCUS ('||v_cols||') SELECT '||v_cols||
         ' FROM BKP_CMV_CUS_20260915_142359';
  EXECUTE IMMEDIATE v_sql;
  v_inseridos:=SQL%ROWCOUNT;

  SELECT COUNT(*) INTO v_depois
    FROM TGFCUS
   WHERE CODPROD IN (2237205918,2237205919,2237205920,2237205921,2237205922,
                     2237205923,2237205924,2237205925,2237205926,2237205927,
                     2237205928,2237205929,2237205930);
  IF v_inseridos<>v_backup OR v_depois<>v_backup THEN
    RAISE_APPLICATION_ERROR(-20394,
      'Validacao do rollback divergiu do backup; a transacao sera revertida.');
  END IF;

  COMMIT;
  DBMS_OUTPUT.PUT_LINE('ID_EXECUCAO=RMD_CMV_CUS_IMS_20260915_142359');
  DBMS_OUTPUT.PUT_LINE('LINHAS_ANTES='||v_antes);
  DBMS_OUTPUT.PUT_LINE('LINHAS_EXCLUIDAS_PARA_RESTAURACAO='||v_excluidos);
  DBMS_OUTPUT.PUT_LINE('LINHAS_REINSERIDAS='||v_inseridos);
  DBMS_OUTPUT.PUT_LINE('LINHAS_DEPOIS='||v_depois);
  DBMS_OUTPUT.PUT_LINE('STATUS=ROLLBACK_EXECUTADO_COMMIT');
EXCEPTION
  WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
END;
