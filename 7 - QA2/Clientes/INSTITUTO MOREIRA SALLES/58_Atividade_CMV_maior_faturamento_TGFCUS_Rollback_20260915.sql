-- Fase: reversao integral do snapshot TGFCUS dos 13 produtos
-- Base: INSTITUTO MOREIRA SALLES
-- Backup: BKP_CMV_CUS_20260915_142359
-- Por seguranca, o rollback nao executa enquanto CONFIRMA_ROLLBACK permanecer NAO.
-- A trigger SANKHYA.TRG_DLT_UPD_TGFCUS deve permanecer DISABLED durante a reversao.

SET DEFINE ON
DEFINE CONFIRMA_ROLLBACK = 'NAO'
SET SERVEROUTPUT ON SIZE UNLIMITED
SET SQLBLANKLINES ON
SET LINESIZE 250
SET PAGESIZE 500
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

