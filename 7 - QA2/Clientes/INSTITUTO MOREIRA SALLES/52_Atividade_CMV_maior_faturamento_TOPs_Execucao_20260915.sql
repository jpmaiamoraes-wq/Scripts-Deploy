PROMPT === CRIACAO DO BACKUP PERSISTENTE ===
CREATE TABLE BKP_CMV_TOP_20260915_140624 AS
SELECT CAST('RMD_CMV_IMS_20260915_140624' AS VARCHAR2(40)) AS ID_EXECUCAO,
       SYSTIMESTAMP AS DH_EXECUCAO,
       CAST(SYS_CONTEXT('USERENV','SESSION_USER') AS VARCHAR2(128)) AS USUARIO_EXECUCAO,
       ROWIDTOCHAR(T.ROWID) AS ROWID_ORIGINAL,
       T.*
  FROM TGFTOP T
 WHERE T.CODTIPOPER IN (1451,1452,1458);

PROMPT === VALIDACAO DO BACKUP ANTES DO UPDATE ===
SELECT ID_EXECUCAO,USUARIO_EXECUCAO,COUNT(*) AS REGISTROS_BACKUP,
       MIN(DH_EXECUCAO) AS DH_BACKUP,
       COUNT(DISTINCT CODTIPOPER) AS TOPS_BACKUP
  FROM BKP_CMV_TOP_20260915_140624
 GROUP BY ID_EXECUCAO,USUARIO_EXECUCAO;

DECLARE
  v_backup NUMBER;
  v_alvo NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_backup FROM BKP_CMV_TOP_20260915_140624;
  SELECT COUNT(*) INTO v_alvo FROM TGFTOP WHERE CODTIPOPER IN (1451,1452,1458);
  IF v_backup<>v_alvo THEN
    RAISE_APPLICATION_ERROR(-20353,
      'Quantidade do backup diverge da quantidade atual das TOPs alvo. Nenhum UPDATE sera aplicado.');
  END IF;
  DBMS_OUTPUT.PUT_LINE('BACKUP_OK=SIM; REGISTROS='||v_backup);
END;
