PROMPT === CONTAGEM FINAL DAS TOPS ALVO ===
SELECT CODTIPOPER,
       COUNT(*) AS VERSOES,
       SUM(CASE WHEN PRECIFICA='N' THEN 1 ELSE 0 END) AS PRECIFICA_N,
       SUM(CASE WHEN NVL(PRECIFICA,'#')<>'N' THEN 1 ELSE 0 END) AS PENDENTES
  FROM TGFTOP
 WHERE CODTIPOPER IN (1451,1452,1458)
 GROUP BY CODTIPOPER
 ORDER BY CODTIPOPER;

