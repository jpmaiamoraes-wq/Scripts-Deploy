PROMPT === INICIO DA EXECUCAO CONTROLADA ===
SELECT SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AS CURRENT_SCHEMA,
       SYS_CONTEXT('USERENV','SESSION_USER') AS SESSION_USER,
       SYS_CONTEXT('USERENV','SERVICE_NAME') AS SERVICE_NAME,
       SYSTIMESTAMP AS DH_EXECUCAO,
       'RMD_CMV_IMS_20260915_140624' AS ID_EXECUCAO
  FROM DUAL;

PROMPT === PREFLIGHT DE SEGURANCA, ANTES DO BACKUP ===
DECLARE
  v_backup NUMBER;
  v_alvo NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_backup
    FROM ALL_OBJECTS
   WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
     AND OBJECT_NAME='BKP_CMV_TOP_20260915_140624';

  IF v_backup>0 THEN
    RAISE_APPLICATION_ERROR(-20351,
      'O backup BKP_CMV_TOP_20260915_140624 ja existe. A execucao foi interrompida para evitar sobreposicao.');
  END IF;

  SELECT COUNT(*) INTO v_alvo
    FROM TGFTOP
   WHERE CODTIPOPER IN (1451,1452,1458);

  IF v_alvo=0 THEN
    RAISE_APPLICATION_ERROR(-20352,
      'Nenhuma versao das TOPs 1451, 1452 ou 1458 foi encontrada.');
  END IF;

  DBMS_OUTPUT.PUT_LINE('PREFLIGHT_OK=SIM; VERSOES_ALVO='||v_alvo);
END;
