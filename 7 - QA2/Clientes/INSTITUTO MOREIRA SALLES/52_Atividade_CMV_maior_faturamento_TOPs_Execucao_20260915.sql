PROMPT === ALTERACAO EXCLUSIVA DE PRECIFICA ===
UPDATE TGFTOP
   SET PRECIFICA='N'
 WHERE CODTIPOPER IN (1451,1452,1458)
   AND NVL(PRECIFICA,'#')<>'N';

PROMPT === VALIDACAO IMEDIATA E COMMIT ===
DECLARE
  v_bad NUMBER;
  v_updated NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_updated
    FROM BKP_CMV_TOP_20260915_140624 B
    JOIN TGFTOP T ON B.ROWID_ORIGINAL=ROWIDTOCHAR(T.ROWID)
   WHERE DECODE(B.PRECIFICA,T.PRECIFICA,1,0)=0;
  SELECT COUNT(*) INTO v_bad
    FROM TGFTOP
   WHERE CODTIPOPER IN (1451,1452,1458)
     AND NVL(PRECIFICA,'#')<>'N';

  IF v_bad>0 THEN
    RAISE_APPLICATION_ERROR(-20354,
      'Persistem versoes alvo com PRECIFICA diferente de N. O bloco sera revertido.');
  END IF;

  COMMIT;
  DBMS_OUTPUT.PUT_LINE('ID_EXECUCAO=RMD_CMV_IMS_20260915_140624');
  DBMS_OUTPUT.PUT_LINE('REGISTROS_ALTERADOS='||v_updated);
  DBMS_OUTPUT.PUT_LINE('TOPS_ALVO=1451,1452,1458');
  DBMS_OUTPUT.PUT_LINE('TOP_1401=FORA_DO_ESCOPO');
  DBMS_OUTPUT.PUT_LINE('STATUS=EXECUTADO_COMMIT');
EXCEPTION
  WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
END;
