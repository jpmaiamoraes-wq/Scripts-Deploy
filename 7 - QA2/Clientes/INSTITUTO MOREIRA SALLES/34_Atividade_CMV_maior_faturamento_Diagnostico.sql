PROMPT === PRODUTOS COM MEDIA DE COMPRA ACIMA DA MEDIA DE VENDA ===
WITH MOVIMENTOS AS (
  SELECT 'C' AS TIPMOV,I.CODPROD,P.DESCRPROD,I.CODVOL,
         C.CODTIPOPER,T.DESCROPER,I.VLRUNIT
    FROM TGFITE I
    JOIN TGFPRO P ON P.CODPROD=I.CODPROD
    JOIN TGFCAB C ON C.NUNOTA=I.NUNOTA AND C.TIPMOV='C'
    JOIN TGFTOP T ON T.CODTIPOPER=C.CODTIPOPER
                  AND T.DHALTER=C.DHTIPOPER
                  AND T.PRECIFICA<>'N'
  UNION ALL
  SELECT 'V' AS TIPMOV,I.CODPROD,P.DESCRPROD,I.CODVOL,
         C.CODTIPOPER,T.DESCROPER,I.VLRUNIT
    FROM TGFITE I
    JOIN TGFPRO P ON P.CODPROD=I.CODPROD
    JOIN TGFCAB C ON C.NUNOTA=I.NUNOTA AND C.TIPMOV='V'
    JOIN TGFTOP T ON T.CODTIPOPER=C.CODTIPOPER
                  AND T.DHALTER=C.DHTIPOPER
                  AND T.GOLSINAL=-1
), RESUMO AS (
  SELECT CODPROD,DESCRPROD,CODVOL,
         AVG(CASE WHEN TIPMOV='C' THEN VLRUNIT END) AS MEDIA_COMPRA,
         AVG(CASE WHEN TIPMOV='V' THEN VLRUNIT END) AS MEDIA_VENDA,
         COUNT(CASE WHEN TIPMOV='C' THEN 1 END) AS ITENS_COMPRA,
         COUNT(CASE WHEN TIPMOV='V' THEN 1 END) AS ITENS_VENDA,
         COUNT(DISTINCT CASE WHEN TIPMOV='C' THEN CODTIPOPER END) AS TOPS_COMPRA,
         COUNT(DISTINCT CASE WHEN TIPMOV='V' THEN CODTIPOPER END) AS TOPS_VENDA
    FROM MOVIMENTOS
   GROUP BY CODPROD,DESCRPROD,CODVOL
)
SELECT CODPROD,DESCRPROD,CODVOL,
       ROUND(MEDIA_COMPRA,2) AS MEDIA_COMPRA,
       ROUND(MEDIA_VENDA,2) AS MEDIA_VENDA,
       ROUND(MEDIA_COMPRA-MEDIA_VENDA,2) AS DIFERENCA,
       ITENS_COMPRA,ITENS_VENDA,TOPS_COMPRA,TOPS_VENDA
  FROM RESUMO
 WHERE MEDIA_COMPRA>MEDIA_VENDA
 ORDER BY DIFERENCA DESC,CODPROD,CODVOL;

