WITH MOVIMENTOS AS (
  SELECT 'C' AS TIPMOV,I.CODPROD,I.CODVOL,I.VLRUNIT
    FROM TGFITE I
    JOIN TGFCAB C ON C.NUNOTA=I.NUNOTA AND C.TIPMOV='C'
    JOIN TGFTOP T ON T.CODTIPOPER=C.CODTIPOPER
                  AND T.DHALTER=C.DHTIPOPER
                  AND T.PRECIFICA<>'N'
  UNION ALL
  SELECT 'V' AS TIPMOV,I.CODPROD,I.CODVOL,I.VLRUNIT
    FROM TGFITE I
    JOIN TGFCAB C ON C.NUNOTA=I.NUNOTA AND C.TIPMOV='V'
    JOIN TGFTOP T ON T.CODTIPOPER=C.CODTIPOPER
                  AND T.DHALTER=C.DHTIPOPER
                  AND T.GOLSINAL=-1
), CANDIDATOS AS (
  SELECT CODPROD,CODVOL
    FROM MOVIMENTOS
   GROUP BY CODPROD,CODVOL
  HAVING AVG(CASE WHEN TIPMOV='C' THEN VLRUNIT END)
       > AVG(CASE WHEN TIPMOV='V' THEN VLRUNIT END)
)
SELECT RTRIM(XMLAGG(XMLELEMENT(E,TO_CHAR(CODPROD)||',') ORDER BY CODPROD)
              .EXTRACT('//text()').getClobVal(),',') AS CODPROD_IN
  FROM (SELECT DISTINCT CODPROD FROM CANDIDATOS);

PROMPT === TOPS DE COMPRA ACIMA DA MEDIA DE VENDA DO PRODUTO ===
WITH COMPRAS AS (
  SELECT I.CODPROD,P.DESCRPROD,I.CODVOL,C.CODTIPOPER,T.DESCROPER,
         AVG(I.VLRUNIT) AS MEDIA_TOP_COMPRA,COUNT(*) AS ITENS_TOP_COMPRA
    FROM TGFITE I
    JOIN TGFPRO P ON P.CODPROD=I.CODPROD
    JOIN TGFCAB C ON C.NUNOTA=I.NUNOTA AND C.TIPMOV='C'
    JOIN TGFTOP T ON T.CODTIPOPER=C.CODTIPOPER
                  AND T.DHALTER=C.DHTIPOPER
                  AND T.PRECIFICA<>'N'
   GROUP BY I.CODPROD,P.DESCRPROD,I.CODVOL,C.CODTIPOPER,T.DESCROPER
), VENDAS AS (
  SELECT I.CODPROD,I.CODVOL,AVG(I.VLRUNIT) AS MEDIA_VENDA
    FROM TGFITE I
    JOIN TGFCAB C ON C.NUNOTA=I.NUNOTA AND C.TIPMOV='V'
    JOIN TGFTOP T ON T.CODTIPOPER=C.CODTIPOPER
                  AND T.DHALTER=C.DHTIPOPER
                  AND T.GOLSINAL=-1
   GROUP BY I.CODPROD,I.CODVOL
)
SELECT C.CODPROD,C.DESCRPROD,C.CODVOL,C.CODTIPOPER,C.DESCROPER,
       ROUND(C.MEDIA_TOP_COMPRA,2) AS MEDIA_TOP_COMPRA,
       ROUND(V.MEDIA_VENDA,2) AS MEDIA_VENDA,
       ROUND(C.MEDIA_TOP_COMPRA-V.MEDIA_VENDA,2) AS DIFERENCA,
       C.ITENS_TOP_COMPRA
  FROM COMPRAS C
  JOIN VENDAS V ON V.CODPROD=C.CODPROD AND V.CODVOL=C.CODVOL
 WHERE C.MEDIA_TOP_COMPRA>V.MEDIA_VENDA
 ORDER BY DIFERENCA DESC,C.CODPROD,C.CODVOL,C.CODTIPOPER;

