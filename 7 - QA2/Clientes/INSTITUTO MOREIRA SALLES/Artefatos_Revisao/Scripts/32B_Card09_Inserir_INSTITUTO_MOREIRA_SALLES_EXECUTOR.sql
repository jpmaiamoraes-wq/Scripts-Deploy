-- Card 09 - inclusao controlada de financeiros derivados de <Dup>.
-- Este executor permanece inofensivo com CONFIRMA_INSERCAO=NAO.
-- A alteracao de TGFFIN/TGFNUM somente ocorre com confirmacao explicita.
-- O mapa desta base usa ID_EXECUCAO_MAPA e status APTO_PARA_INSERCAO_CONTROLADA.

SET DEFINE ON
SET SERVEROUTPUT ON SIZE UNLIMITED
SET SQLBLANKLINES ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DEFINE ID_EXECUCAO = 'RMD_FDUP_IMS_20260914165524'
DEFINE TBL_PPG = 'BKP_RMD_IMS_DUP_PPG_20260914'
DEFINE TBL_INS = 'BKP_RMD_IMS_DUP_INS_20260914'
DEFINE CONFIRMA_INSERCAO = 'NAO'

PROMPT === CARD 09 - INSERT CONTROLADO TGFFIN - INSTITUTO MOREIRA SALLES ===

DECLARE
  v_qtd NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_qtd
    FROM ALL_TABLES
   WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
     AND TABLE_NAME='&TBL_INS';
  IF v_qtd=0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE &TBL_INS (
        ID_EXECUCAO VARCHAR2(40) NOT NULL,
        DH_EXECUCAO TIMESTAMP NOT NULL,
        NUNOTA NUMBER NOT NULL,
        NUFIN NUMBER NOT NULL,
        VLRDESDOB NUMBER,
        DTVENC DATE,
        CODCTABCOINT NUMBER,
        CODTIPTIT NUMBER,
        NDUP_XML VARCHAR2(4000)
      )]';
    DBMS_OUTPUT.PUT_LINE('AUDITORIA_CRIADA=&TBL_INS');
  ELSE
    DBMS_OUTPUT.PUT_LINE('AUDITORIA_EXISTENTE=&TBL_INS');
  END IF;
END;
/

