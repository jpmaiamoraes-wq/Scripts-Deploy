  SELECT COUNT(*), COUNT(DISTINCT NUNOTA)
    INTO v_qtd, v_distinct
    FROM &TBL_PPG
   WHERE ID_EXECUCAO_MAPA='&ID_EXECUCAO'
     AND STATUS_MAPA='APTO_PARA_INSERCAO_CONTROLADA';
  DBMS_OUTPUT.PUT_LINE('LINHAS_APTAS='||v_qtd||'; NOTAS_APTAS='||v_distinct);
  IF v_qtd <> 24 OR v_distinct <> 24 THEN
    RAISE_APPLICATION_ERROR(-20324,
      'Quantidade apta divergente: esperado 24 linhas e 24 notas.');
  END IF;

  SELECT COUNT(*) INTO v_qtd
    FROM &TBL_PPG M
   WHERE M.ID_EXECUCAO_MAPA='&ID_EXECUCAO'
     AND M.STATUS_MAPA='APTO_PARA_INSERCAO_CONTROLADA'
     AND (M.VDUP_XML IS NULL
       OR NOT REGEXP_LIKE(TRIM(M.VDUP_XML),'^[0-9]+([.][0-9]+)?$')
       OR M.DVENC_XML IS NULL
       OR NOT REGEXP_LIKE(TRIM(M.DVENC_XML),'^[0-9]{4}-[0-9]{2}-[0-9]{2}$')
       OR M.CODTIPTITPAD IS NULL
       OR NOT EXISTS (SELECT 1 FROM TGFTIT T WHERE T.CODTIPTIT=M.CODTIPTITPAD)
       OR M.QTD_TGFTPV_EXATA <> 1
       OR M.CODCTABCOINT_RESOLVIDO IS NULL
       OR M.QTD_TGFNUM_TGFFIN <> 1
       OR M.QTD_TGFFIN_ATUAL <> 0
       OR M.QTD_LINHAS_APTAS_NUNOTA <> 1
       OR M.RECDESP_RESOLVIDO=0);
  IF v_qtd > 0 THEN
    RAISE_APPLICATION_ERROR(-20325,
      'Uma ou mais linhas aptas falharam na validacao consolidada.');
  END IF;

  SELECT COUNT(DISTINCT F.NUNOTA) INTO v_existentes
    FROM TGFFIN F
    JOIN &TBL_PPG M
      ON M.NUNOTA=F.NUNOTA
     AND M.ID_EXECUCAO_MAPA='&ID_EXECUCAO'
     AND M.STATUS_MAPA='APTO_PARA_INSERCAO_CONTROLADA';
  SELECT COUNT(*) INTO v_pendentes
    FROM &TBL_PPG M
   WHERE M.ID_EXECUCAO_MAPA='&ID_EXECUCAO'
     AND M.STATUS_MAPA='APTO_PARA_INSERCAO_CONTROLADA'
     AND NOT EXISTS (SELECT 1 FROM TGFFIN F WHERE F.NUNOTA=M.NUNOTA);
  DBMS_OUTPUT.PUT_LINE('JA_EXISTIAM_TGFFIN='||v_existentes);
  DBMS_OUTPUT.PUT_LINE('PENDENTES_PARA_INSERCAO='||v_pendentes);
  IF v_pendentes = 0 THEN
    DBMS_OUTPUT.PUT_LINE('STATUS=SEM_PENDENTES_PARA_INSERCAO');
    RETURN;
  END IF;

  SELECT COUNT(*) INTO v_qtd
    FROM &TBL_PPG M
   WHERE M.ID_EXECUCAO_MAPA='&ID_EXECUCAO'
     AND M.STATUS_MAPA='APTO_PARA_INSERCAO_CONTROLADA'
     AND NOT EXISTS (
       SELECT 1 FROM TGFTPV V
        WHERE V.CODTIPVENDA=M.CODTIPVENDA
          AND V.DHALTER=M.DHTIPVENDA);
  IF v_qtd > 0 THEN
    RAISE_APPLICATION_ERROR(-20329,
      'Uma ou mais notas nao possuem a versao exata da TGFTPV usada no cabecalho.');
  END IF;

  SELECT COUNT(*) INTO v_tgfnum_rows
    FROM TGFNUM WHERE ARQUIVO='TGFFIN';
  DBMS_OUTPUT.PUT_LINE('TGFNUM_TGFFIN_ROWS='||v_tgfnum_rows);
  IF v_tgfnum_rows <> 1 THEN
    FOR t IN (SELECT ARQUIVO, ULTCOD FROM TGFNUM
               WHERE ARQUIVO='TGFFIN' ORDER BY ULTCOD) LOOP
      DBMS_OUTPUT.PUT_LINE('TGFNUM_ROW ARQUIVO='||t.ARQUIVO||' ULTCOD='||t.ULTCOD);
    END LOOP;
    RAISE_APPLICATION_ERROR(-20326,
      'TGFNUM deve possuir exatamente uma linha para TGFFIN.');
  END IF;

  IF v_confirm <> 'SIM' THEN
    DBMS_OUTPUT.PUT_LINE(
      'STATUS=NAO_EXECUTADO; confirme explicitamente antes de alterar TGFFIN/TGFNUM.');
    RETURN;
  END IF;

  DBMS_OUTPUT.PUT_LINE('ANTES_LOCK_TGFNUM');
  SELECT ULTCOD INTO v_ultcod
    FROM TGFNUM WHERE ARQUIVO='TGFFIN' FOR UPDATE WAIT 5;
  DBMS_OUTPUT.PUT_LINE('APOS_LOCK_TGFNUM ULTCOD='||v_ultcod);

  SELECT COUNT(*) INTO v_qtd FROM &TBL_INS
   WHERE ID_EXECUCAO='&ID_EXECUCAO';
  IF v_qtd > 0 THEN
    RAISE_APPLICATION_ERROR(-20327,
      'Ja existem inclusoes auditadas para este ID_EXECUCAO.');
  END IF;

  FOR r IN (
    SELECT M.*
      FROM &TBL_PPG M
     WHERE M.ID_EXECUCAO_MAPA='&ID_EXECUCAO'
       AND M.STATUS_MAPA='APTO_PARA_INSERCAO_CONTROLADA'
       AND NOT EXISTS (SELECT 1 FROM TGFFIN F WHERE F.NUNOTA=M.NUNOTA)
     ORDER BY M.NUNOTA, M.SEQ_PPG
  ) LOOP
    v_nufin := v_ultcod + 1;
    DBMS_OUTPUT.PUT_LINE('PROCESSANDO NUNOTA='||r.NUNOTA||
      ' NUFIN='||v_nufin||' VDUP='||r.VDUP_XML||
      ' DVENC='||r.DVENC_XML||' NDUP='||NVL(r.NDUP_XML,'<NULL>'));
    BEGIN
      v_vldup := TO_NUMBER(TRIM(r.VDUP_XML),
                           '999999999999999999D99999999',
