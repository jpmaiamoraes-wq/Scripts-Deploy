  v_tgfnum_rows NUMBER;
  v_ultcod TGFNUM.ULTCOD%TYPE;
  v_nufin TGFFIN.NUFIN%TYPE;
  v_vldup TGFFIN.VLRDESDOB%TYPE;
  v_dvenc TGFFIN.DTVENC%TYPE;
  v_inseridos NUMBER := 0;
