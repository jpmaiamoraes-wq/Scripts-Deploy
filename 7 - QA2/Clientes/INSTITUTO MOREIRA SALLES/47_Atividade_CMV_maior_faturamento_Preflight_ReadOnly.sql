SELECT T.CODTIPOPER,T.DHALTER,T.DESCROPER,T.PRECIFICA,T.ATUALEST,T.ATUALULTIMACOMP,
       T.ATUALULTIMAVEND,T.GOLSINAL,
       COUNT(DISTINCT C.NUNOTA) AS NOTAS,
       COUNT(I.CODPROD) AS ITENS,
       ROUND(AVG(I.VLRUNIT),2) AS MEDIA_VLRUNIT,
       SUM(NVL(I.QTDNEG,0)) AS QTD
  FROM TGFTOP T
  LEFT JOIN TGFCAB C ON C.CODTIPOPER=T.CODTIPOPER AND C.DHTIPOPER=T.DHALTER AND C.TIPMOV='C'
  LEFT JOIN TGFITE I ON I.NUNOTA=C.NUNOTA
                       AND I.CODPROD IN (1451604,2237205918,2237205919,2237205920,2237205921,2237205922,2237205923,2237205924,2237205925,2237205926,2237205927,2237205928,2237205929,2237205930)
 WHERE T.CODTIPOPER IN (1401,1451,1452,1458)
 GROUP BY T.CODTIPOPER,T.DHALTER,T.DESCROPER,T.PRECIFICA,T.ATUALEST,T.ATUALULTIMACOMP,T.ATUALULTIMAVEND,T.GOLSINAL
 ORDER BY T.CODTIPOPER,T.DHALTER;

PROMPT === MOVIMENTOS DOS PRODUTOS POR TOP ===
SELECT C.CODTIPOPER,T.DESCROPER,I.CODPROD,P.DESCRPROD,
       COUNT(DISTINCT C.NUNOTA) AS NOTAS,
       COUNT(*) AS ITENS,
       ROUND(AVG(I.VLRUNIT),2) AS MEDIA_VLRUNIT,
       ROUND(SUM(NVL(I.VLRTOT,0)),2) AS TOTAL_ITEM,
       SUM(NVL(I.QTDNEG,0)) AS QTD
  FROM TGFCAB C
  JOIN TGFITE I ON I.NUNOTA=C.NUNOTA
  JOIN TGFPRO P ON P.CODPROD=I.CODPROD
  JOIN TGFTOP T ON T.CODTIPOPER=C.CODTIPOPER AND T.DHALTER=C.DHTIPOPER
 WHERE C.TIPMOV='C'
   AND C.CODTIPOPER IN (1401,1451,1452,1458)
   AND I.CODPROD IN (1451604,2237205918,2237205919,2237205920,2237205921,2237205922,2237205923,2237205924,2237205925,2237205926,2237205927,2237205928,2237205929,2237205930)
 GROUP BY C.CODTIPOPER,T.DESCROPER,I.CODPROD,P.DESCRPROD
 ORDER BY C.CODTIPOPER,I.CODPROD;

PROMPT === TGFCUS POR PRODUTO ===
SELECT CODPROD,
       COUNT(*) AS LINHAS_TGFCUS,
       SUM(CASE WHEN DTATUAL=DATE '1900-01-01' THEN 1 ELSE 0 END) AS LINHAS_DATA_1900,
       SUM(CASE WHEN DTATUAL=DATE '1900-01-01' AND NVL(CUSSEMICM,0)=0 THEN 1 ELSE 0 END) AS OBSOLETAS_CANDIDATAS,
       MIN(DTATUAL) AS PRIMEIRA_DATA,
       MAX(DTATUAL) AS ULTIMA_DATA
  FROM TGFCUS
 WHERE CODPROD IN (1451604,2237205918,2237205919,2237205920,2237205921,2237205922,2237205923,2237205924,2237205925,2237205926,2237205927,2237205928,2237205929,2237205930)
 GROUP BY CODPROD
 ORDER BY CODPROD;

