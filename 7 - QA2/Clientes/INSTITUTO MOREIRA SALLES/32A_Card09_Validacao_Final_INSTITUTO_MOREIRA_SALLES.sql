SELECT COUNT(*) AS LINHAS_APTAS,
       COUNT(DISTINCT NUNOTA) AS NOTAS_APTAS,
       SUM(CASE WHEN REGEXP_LIKE(TRIM(VDUP_XML),'^[0-9]+([.][0-9]+)?$') THEN 1 ELSE 0 END) AS VDUP_NUMERICO,
       SUM(CASE WHEN REGEXP_LIKE(TRIM(DVENC_XML),'^[0-9]{4}-[0-9]{2}-[0-9]{2}$') THEN 1 ELSE 0 END) AS DVENC_VALIDO,
       SUM(CASE WHEN CODTIPTITPAD IS NOT NULL
                  AND EXISTS (SELECT 1 FROM TGFTIT T WHERE T.CODTIPTIT= M.CODTIPTITPAD)
                THEN 1 ELSE 0 END) AS TITULOS_VALIDOS,
       SUM(CASE WHEN QTD_TGFTPV_EXATA=1 THEN 1 ELSE 0 END) AS TGFTPV_EXATA,
       SUM(CASE WHEN CODCTABCOINT_RESOLVIDO IS NOT NULL THEN 1 ELSE 0 END) AS CONTAS_RESOLVIDAS,
       SUM(CASE WHEN QTD_TGFFIN_ATUAL=0 THEN 1 ELSE 0 END) AS SEM_TGFFIN,
       SUM(CASE WHEN QTD_TGFNUM_TGFFIN=1 THEN 1 ELSE 0 END) AS TGFNUM_UNICO,
       SUM(CASE WHEN QTD_LINHAS_APTAS_NUNOTA=1 THEN 1 ELSE 0 END) AS UMA_LINHA_POR_NOTA
  FROM BKP_RMD_IMS_DUP_PPG_20260914 M
 WHERE STATUS_MAPA='APTO_PARA_INSERCAO_CONTROLADA';

