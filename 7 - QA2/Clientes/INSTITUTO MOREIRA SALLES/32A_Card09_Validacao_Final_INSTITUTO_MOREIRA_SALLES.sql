SELECT CASE
         WHEN COUNT(*)=24
          AND COUNT(DISTINCT NUNOTA)=24
          AND SUM(CASE WHEN REGEXP_LIKE(TRIM(VDUP_XML),'^[0-9]+([.][0-9]+)?$') THEN 1 ELSE 0 END)=24
          AND SUM(CASE WHEN REGEXP_LIKE(TRIM(DVENC_XML),'^[0-9]{4}-[0-9]{2}-[0-9]{2}$') THEN 1 ELSE 0 END)=24
          AND SUM(CASE WHEN CODTIPTITPAD IS NOT NULL
                         AND EXISTS (SELECT 1 FROM TGFTIT T WHERE T.CODTIPTIT= M.CODTIPTITPAD)
                       THEN 1 ELSE 0 END)=24
          AND SUM(CASE WHEN QTD_TGFTPV_EXATA=1 THEN 1 ELSE 0 END)=24
          AND SUM(CASE WHEN CODCTABCOINT_RESOLVIDO IS NOT NULL THEN 1 ELSE 0 END)=24
          AND SUM(CASE WHEN QTD_TGFFIN_ATUAL=0 THEN 1 ELSE 0 END)=24
          AND SUM(CASE WHEN QTD_TGFNUM_TGFFIN=1 THEN 1 ELSE 0 END)=24
          AND SUM(CASE WHEN QTD_LINHAS_APTAS_NUNOTA=1 THEN 1 ELSE 0 END)=24
         THEN 'APTO_PARA_CONFIRMACAO_DE_INSERCAO'
         ELSE 'BLOQUEAR_INSERCAO_E_REVISAR'
       END AS STATUS_VALIDACAO_FINAL
  FROM BKP_RMD_IMS_DUP_PPG_20260914 M
 WHERE STATUS_MAPA='APTO_PARA_INSERCAO_CONTROLADA';

