DECLARE
  v_backup NUMBER;
  v_atual NUMBER;
  v_duplicados NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_backup FROM BKP_CMV_CUS_20260915_142359;
  SELECT COUNT(*) INTO v_atual
    FROM TGFCUS
   WHERE CODPROD IN (2237205918,2237205919,2237205920,2237205921,2237205922,
                     2237205923,2237205924,2237205925,2237205926,2237205927,
                     2237205928,2237205929,2237205930);
  IF v_backup<>v_atual THEN
    RAISE_APPLICATION_ERROR(-20383,
      'Quantidade do snapshot diverge da TGFCUS atual. Backup preservado; nenhuma linha de TGFCUS foi alterada.');
  END IF;

  SELECT COUNT(*) INTO v_duplicados
    FROM (SELECT CODPROD,CODEMP,DTATUAL,CODLOCAL,CONTROLE,NUNOTA,SEQUENCIA,
                 COUNT(*) AS QTD
            FROM BKP_CMV_CUS_20260915_142359
           GROUP BY CODPROD,CODEMP,DTATUAL,CODLOCAL,CONTROLE,NUNOTA,SEQUENCIA
          HAVING COUNT(*)>1);
  IF v_duplicados>0 THEN
    RAISE_APPLICATION_ERROR(-20384,
      'O snapshot possui chaves PK duplicadas; reversao automatica nao e segura.');
  END IF;

  DBMS_OUTPUT.PUT_LINE('BACKUP_OK=SIM; REGISTROS='||v_backup||'; PRODUTOS=13');
  DBMS_OUTPUT.PUT_LINE('STATUS=SNAPSHOT_PERSISTENTE_CRIADO');
END;
