SELECT C.CONSTRAINT_NAME,C.CONSTRAINT_TYPE,
       LISTAGG(CC.COLUMN_NAME,',') WITHIN GROUP(ORDER BY CC.POSITION) AS COLUNAS
  FROM ALL_CONSTRAINTS C
  JOIN ALL_CONS_COLUMNS CC ON CC.OWNER=C.OWNER AND CC.CONSTRAINT_NAME=C.CONSTRAINT_NAME
 WHERE C.OWNER='SANKHYA' AND C.TABLE_NAME='TGFCUS'
   AND C.CONSTRAINT_TYPE IN ('P','U')
 GROUP BY C.CONSTRAINT_NAME,C.CONSTRAINT_TYPE
 ORDER BY C.CONSTRAINT_NAME;

SELECT INDEX_NAME,UNIQUENESS,
       LISTAGG(COLUMN_NAME,',') WITHIN GROUP(ORDER BY COLUMN_POSITION) AS COLUNAS
  FROM ALL_IND_COLUMNS
 WHERE TABLE_OWNER='SANKHYA' AND TABLE_NAME='TGFCUS'
 GROUP BY INDEX_NAME,UNIQUENESS
 ORDER BY INDEX_NAME;

SELECT CODPROD,CODEMP,TO_CHAR(DTATUAL,'YYYY-MM-DD') AS DTATUAL,CODLOCAL,CONTROLE,
       CUSMEDICM,CUSSEMICM,CUSMED,QTDNEG,CUSMEDCALC,AUTOMATICO,RECARGA
  FROM TGFCUS
 WHERE CODPROD IN (1451604,2237205918,2237205919,2237205920,2237205921,2237205922,2237205923,2237205924,2237205925,2237205926,2237205927,2237205928,2237205929,2237205930)
   AND DTATUAL=DATE '1900-01-01'
 ORDER BY CODPROD,CODEMP,CODLOCAL,CONTROLE;

SELECT CODPROD,COUNT(*) AS LINHAS_TGFCUSITE,MIN(DTATUAL) AS PRIMEIRA_DATA,MAX(DTATUAL) AS ULTIMA_DATA
  FROM TGFCUSITE
 WHERE CODPROD IN (1451604,2237205918,2237205919,2237205920,2237205921,2237205922,2237205923,2237205924,2237205925,2237205926,2237205927,2237205928,2237205929,2237205930)
 GROUP BY CODPROD
 ORDER BY CODPROD;

SELECT TRIGGER_NAME,STATUS,TRIGGERING_EVENT,TRIGGER_TYPE
  FROM ALL_TRIGGERS
