PROMPT === TABELAS E COLUNAS FISICAS CODBAI/CODEND ===
SELECT COUNT(*) AS COLUNAS_FISICAS,
       COUNT(DISTINCT C.TABLE_NAME) AS TABELAS_FISICAS,
       SUM(CASE WHEN C.COLUMN_NAME='CODBAI' THEN 1 ELSE 0 END) AS COLUNAS_CODBAI,
       SUM(CASE WHEN C.COLUMN_NAME='CODEND' THEN 1 ELSE 0 END) AS COLUNAS_CODEND
  FROM ALL_TAB_COLUMNS C
  JOIN ALL_TABLES T ON T.OWNER=C.OWNER AND T.TABLE_NAME=C.TABLE_NAME
 WHERE C.OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
   AND C.COLUMN_NAME IN ('CODBAI','CODEND')
;

