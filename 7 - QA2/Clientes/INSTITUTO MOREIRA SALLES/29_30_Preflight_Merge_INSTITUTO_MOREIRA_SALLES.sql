PROMPT === INVENTARIO DE FKS PARA TSIBAI/TSIEND (INCLUI COMPOSTAS) ===
SELECT P.TABLE_NAME AS PARENT_TABLE,
       COUNT(DISTINCT C.CONSTRAINT_NAME) AS FK_CONSTRAINTS,
       COUNT(DISTINCT C.TABLE_NAME) AS CHILD_TABLES,
       COUNT(*) AS FK_COLUMNS,
       SUM(CASE WHEN CC.POSITION>1 THEN 1 ELSE 0 END) AS COMPOSITE_COLUMNS
  FROM ALL_CONSTRAINTS C
  JOIN ALL_CONS_COLUMNS CC
    ON CC.OWNER=C.OWNER AND CC.CONSTRAINT_NAME=C.CONSTRAINT_NAME
  JOIN ALL_CONSTRAINTS P
    ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
 WHERE C.OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
   AND C.CONSTRAINT_TYPE='R'
   AND P.TABLE_NAME IN ('TSIBAI','TSIEND')
 GROUP BY P.TABLE_NAME
 ORDER BY P.TABLE_NAME;

PROMPT === PKS/UKS DAS TABELAS COM DEPENDENCIA OU COLUNA CODBAI/CODEND ===
SELECT C.CONSTRAINT_TYPE,
       COUNT(DISTINCT C.CONSTRAINT_NAME) AS CONSTRAINTS,
       COUNT(DISTINCT C.TABLE_NAME) AS TABLES_WITH_KEYS,
       COUNT(*) AS KEY_COLUMNS,
       SUM(CASE WHEN CC.POSITION>1 THEN 1 ELSE 0 END) AS COMPOSITE_COLUMNS
  FROM ALL_CONSTRAINTS C
  JOIN ALL_CONS_COLUMNS CC
    ON CC.OWNER=C.OWNER AND CC.CONSTRAINT_NAME=C.CONSTRAINT_NAME
 WHERE C.OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
   AND C.CONSTRAINT_TYPE IN ('P','U')
   AND (
        C.TABLE_NAME IN (
          SELECT DISTINCT R.TABLE_NAME
            FROM ALL_CONSTRAINTS R
            JOIN ALL_CONSTRAINTS P
              ON P.OWNER=R.R_OWNER AND P.CONSTRAINT_NAME=R.R_CONSTRAINT_NAME
           WHERE R.OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
             AND R.CONSTRAINT_TYPE='R'
             AND P.TABLE_NAME IN ('TSIBAI','TSIEND')
        )
        OR EXISTS (
          SELECT 1 FROM ALL_CONS_COLUMNS X
           WHERE X.OWNER=C.OWNER
             AND X.CONSTRAINT_NAME=C.CONSTRAINT_NAME
             AND X.COLUMN_NAME IN ('CODBAI','CODEND')
        )
       )
 GROUP BY C.CONSTRAINT_TYPE
 ORDER BY C.CONSTRAINT_TYPE;

