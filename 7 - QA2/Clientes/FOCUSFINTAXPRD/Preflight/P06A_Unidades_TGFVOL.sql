SELECT CODVOL,DESCRVOL,
       CASE WHEN REGEXP_LIKE(CODVOL,'[0-9]') THEN 'IGNORAR_NUMERAL'
            WHEN DESCRVOL<>UPPER(DESCRVOL) THEN 'DESCRICAO_MINUSCULA'
            ELSE 'AVALIAR' END SITUACAO
FROM TGFVOL
ORDER BY CODVOL
