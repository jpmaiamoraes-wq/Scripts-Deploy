SELECT 'MAPA_TOTAL' AS INDICADOR, COUNT(*) AS QUANTIDADE
  FROM RMD_JCLM_MRG_20260919
 WHERE ID_EXECUCAO='JCLM_MRG_20260919_01'
UNION ALL
SELECT 'MAPA_BAI', COUNT(*)
  FROM RMD_JCLM_MRG_20260919
 WHERE ID_EXECUCAO='JCLM_MRG_20260919_01' AND TIPO='BAI'
UNION ALL
SELECT 'MAPA_END', COUNT(*)
  FROM RMD_JCLM_MRG_20260919
 WHERE ID_EXECUCAO='JCLM_MRG_20260919_01' AND TIPO='END'
UNION ALL
SELECT 'BACKUP_BAI', COUNT(*)
  FROM RMD_JCLM_MRG_20260919_BAI
 WHERE ID_EXECUCAO='JCLM_MRG_20260919_01'
UNION ALL
SELECT 'BACKUP_END', COUNT(*)
  FROM RMD_JCLM_MRG_20260919_END
 WHERE ID_EXECUCAO='JCLM_MRG_20260919_01'
UNION ALL
SELECT 'DEPENDENCIAS_AUDITADAS', COUNT(*)
  FROM RMD_JCLM_MRG_20260919_DEP
 WHERE ID_EXECUCAO='JCLM_MRG_20260919_01'
UNION ALL
SELECT 'EXCECOES', COUNT(*)
  FROM RMD_JCLM_MRG_20260919_EXC
 WHERE ID_EXECUCAO='JCLM_MRG_20260919_01'
UNION ALL
SELECT 'BAI_OBSOLETOS_REMANESCENTES', COUNT(*)
  FROM TSIBAI
 WHERE CODBAI IN (SELECT COD_OBSOLETO FROM RMD_JCLM_MRG_20260919 WHERE ID_EXECUCAO='JCLM_MRG_20260919_01' AND TIPO='BAI')
UNION ALL
SELECT 'END_OBSOLETOS_REMANESCENTES', COUNT(*)
  FROM TSIEND
 WHERE CODEND IN (SELECT COD_OBSOLETO FROM RMD_JCLM_MRG_20260919 WHERE ID_EXECUCAO='JCLM_MRG_20260919_01' AND TIPO='END')
ORDER BY 1;
