SELECT 'MAPA_BAI' AS INDICADOR, COUNT(*) AS QUANTIDADE
  FROM RMD_JCLM_MRG_20260919
 WHERE ID_EXECUCAO='JCLM_MRG_20260919_01' AND TIPO='BAI'
UNION ALL
SELECT 'MAPA_END', COUNT(*)
  FROM RMD_JCLM_MRG_20260919
 WHERE ID_EXECUCAO='JCLM_MRG_20260919_01' AND TIPO='END'
UNION ALL
SELECT 'BAI_MAPA_COM_PAI_ATUAL', COUNT(*)
  FROM RMD_JCLM_MRG_20260919 M
  JOIN TSIBAI B ON B.CODBAI=M.COD_OBSOLETO
 WHERE M.ID_EXECUCAO='JCLM_MRG_20260919_01' AND M.TIPO='BAI'
UNION ALL
SELECT 'END_MAPA_COM_PAI_ATUAL', COUNT(*)
  FROM RMD_JCLM_MRG_20260919 M
  JOIN TSIEND E ON E.CODEND=M.COD_OBSOLETO
 WHERE M.ID_EXECUCAO='JCLM_MRG_20260919_01' AND M.TIPO='END'
UNION ALL
SELECT 'BACKUP_BAI', COUNT(*)
  FROM RMD_JCLM_MRG_20260919_BAI
 WHERE ID_EXECUCAO='JCLM_MRG_20260919_01'
UNION ALL
SELECT 'BACKUP_END', COUNT(*)
  FROM RMD_JCLM_MRG_20260919_END
 WHERE ID_EXECUCAO='JCLM_MRG_20260919_01'
UNION ALL
SELECT 'DEPENDENCIAS_AUDITADAS', COUNT(*)
  FROM RMD_JCLM_MRG_20260919_DEP
 WHERE ID_EXECUCAO='JCLM_MRG_20260919_01'
UNION ALL
SELECT 'EXCECOES', COUNT(*)
  FROM RMD_JCLM_MRG_20260919_EXC
 WHERE ID_EXECUCAO='JCLM_MRG_20260919_01'
ORDER BY 1
