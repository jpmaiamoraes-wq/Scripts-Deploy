-- Destino preservado: 1619. Origem removida: 2667.
-- DTCAD e DTALTER sao campos de auditoria e nao impedem a equivalencia cadastral.
SET SERVEROUTPUT ON SIZE UNLIMITED;
SET DEFINE OFF;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

-- DDL isolado: as tabelas precisam existir antes da compilacao do bloco funcional.
DECLARE
  N NUMBER;
  PROCEDURE CRIA(P_NOME VARCHAR2, P_DDL VARCHAR2) IS
  BEGIN
    SELECT COUNT(*) INTO N FROM ALL_TABLES
     WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND TABLE_NAME=UPPER(P_NOME);
    IF N=0 THEN EXECUTE IMMEDIATE P_DDL; END IF;
  END;
BEGIN
  IF UPPER(SYS_CONTEXT('USERENV','SERVICE_NAME')) NOT LIKE 'MEGANETRJPRD%' THEN
    RAISE_APPLICATION_ERROR(-20500,'Conexao nao e MEGANETRJPRD. Operacao bloqueada.');
  END IF;
  CRIA('BKP_MPC_MAP_MEGANET',
    'CREATE TABLE BKP_MPC_MAP_MEGANET (ID_EXECUCAO VARCHAR2(30),DH_EXECUCAO TIMESTAMP,USUARIO_EXECUCAO VARCHAR2(128),CODPARC_ORIGEM NUMBER,CODPARC_DESTINO NUMBER,CGC_CPF VARCHAR2(30))');
  CRIA('BKP_MPC_REF_MEGANET',
    'CREATE TABLE BKP_MPC_REF_MEGANET (ID_EXECUCAO VARCHAR2(30),DH_EXECUCAO TIMESTAMP,OWNER_REF VARCHAR2(128),TABELA_REF VARCHAR2(128),COLUNA_REF VARCHAR2(128),ROWID_ORIGINAL VARCHAR2(30),CODPARC_ANTES NUMBER,CODPARC_DEPOIS NUMBER)');
  CRIA('BKP_MPC_PAR_MEGANET',
    'CREATE TABLE BKP_MPC_PAR_MEGANET AS SELECT CAST(NULL AS VARCHAR2(30)) ID_EXECUCAO,CAST(NULL AS TIMESTAMP) DH_EXECUCAO,CAST(NULL AS VARCHAR2(128)) USUARIO_EXECUCAO,T.* FROM TGFPAR T WHERE 1=0');
  CRIA('BKP_MPC_TGFCPP_MEGANET',
    'CREATE TABLE BKP_MPC_TGFCPP_MEGANET AS SELECT CAST(NULL AS VARCHAR2(30)) ID_EXECUCAO,CAST(NULL AS TIMESTAMP) DH_EXECUCAO,CAST(NULL AS VARCHAR2(10)) PAPEL,T.* FROM TGFCPP T WHERE 1=0');
  DBMS_OUTPUT.PUT_LINE('ESTRUTURAS_DE_BACKUP=OK');
END;
