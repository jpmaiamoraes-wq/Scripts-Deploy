DECLARE
  V_QTD NUMBER;
BEGIN
  FOR R IN (
    WITH FKS AS (
      SELECT C.OWNER, C.TABLE_NAME, CC.COLUMN_NAME
        FROM ALL_CONSTRAINTS C
        JOIN ALL_CONS_COLUMNS CC ON CC.OWNER=C.OWNER AND CC.CONSTRAINT_NAME=C.CONSTRAINT_NAME
        JOIN ALL_CONSTRAINTS P ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
        JOIN ALL_CONS_COLUMNS PC ON PC.OWNER=P.OWNER AND PC.CONSTRAINT_NAME=P.CONSTRAINT_NAME AND PC.POSITION=CC.POSITION
       WHERE C.CONSTRAINT_TYPE='R' AND C.STATUS='ENABLED'
         AND P.OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND P.TABLE_NAME='TGFPAR'
         AND PC.COLUMN_NAME='CODPARC'
         AND (SELECT COUNT(*) FROM ALL_CONS_COLUMNS X WHERE X.OWNER=C.OWNER AND X.CONSTRAINT_NAME=C.CONSTRAINT_NAME)=1
    ), NOMINAIS AS (
      SELECT C.OWNER, C.TABLE_NAME, C.COLUMN_NAME
        FROM ALL_TAB_COLUMNS C
        JOIN ALL_TABLES T ON T.OWNER=C.OWNER AND T.TABLE_NAME=C.TABLE_NAME
       WHERE C.OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND C.COLUMN_NAME='CODPARC'
    )
    SELECT DISTINCT OWNER, TABLE_NAME, COLUMN_NAME FROM (
      SELECT * FROM FKS UNION ALL SELECT * FROM NOMINAIS
    ) WHERE NOT (TABLE_NAME='TGFPAR' AND COLUMN_NAME='CODPARC')
      AND TABLE_NAME NOT LIKE 'BKP\_%' ESCAPE '\'
      AND TABLE_NAME NOT LIKE '%\_BKP' ESCAPE '\'
    ORDER BY OWNER,TABLE_NAME,COLUMN_NAME
  ) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM "'||R.OWNER||'"."'||R.TABLE_NAME||
                        '" WHERE "'||R.COLUMN_NAME||'" = 2667' INTO V_QTD;
      IF V_QTD>0 THEN
        DBMS_OUTPUT.PUT_LINE(R.OWNER||'.'||R.TABLE_NAME||'.'||R.COLUMN_NAME||'='||V_QTD);
      END IF;
    EXCEPTION WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('NAO_LIDA='||R.OWNER||'.'||R.TABLE_NAME||'.'||R.COLUMN_NAME||';ERRO='||SQLERRM);
    END;
  END LOOP;
END;
