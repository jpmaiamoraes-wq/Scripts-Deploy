DECLARE
  V_COLS VARCHAR2(32767);
  V_SQL  VARCHAR2(32767);
  V_DIF  NUMBER;
  PROCEDURE COMPARA(P_A NUMBER, P_B NUMBER) IS
  BEGIN
    V_SQL := 'SELECT COUNT(*) FROM ('||
             'SELECT '||V_COLS||' FROM TGFPAR WHERE CODPARC='||P_A||
             ' MINUS SELECT '||V_COLS||' FROM TGFPAR WHERE CODPARC='||P_B||
             ' UNION ALL SELECT '||V_COLS||' FROM TGFPAR WHERE CODPARC='||P_B||
             ' MINUS SELECT '||V_COLS||' FROM TGFPAR WHERE CODPARC='||P_A||')';
    EXECUTE IMMEDIATE V_SQL INTO V_DIF;
    DBMS_OUTPUT.PUT_LINE('PAR='||P_A||'/'||P_B||';DIFERENCAS='||V_DIF||
      CASE WHEN V_DIF=0 THEN ';STATUS=IDENTICOS_NOS_CAMPOS_COMPARAVEIS'
           ELSE ';STATUS=DIVERGENTES_NAO_EXECUTAR' END);
  END;
BEGIN
  SELECT LISTAGG('"'||COLUMN_NAME||'"', ',') WITHIN GROUP (ORDER BY COLUMN_ID)
    INTO V_COLS
    FROM ALL_TAB_COLUMNS
   WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
     AND TABLE_NAME='TGFPAR'
     AND COLUMN_NAME NOT IN ('CODPARC','DTCAD','DTALTER')
     AND DATA_TYPE NOT IN ('BLOB','CLOB','NCLOB','LONG','LONG RAW','BFILE','XMLTYPE');
  COMPARA(2667,1619);
  DBMS_OUTPUT.PUT_LINE('PAR=2689/481;STATUS=FORA_DO_ESCOPO_POR_DIVERGENCIA_CADASTRAL');
END;
