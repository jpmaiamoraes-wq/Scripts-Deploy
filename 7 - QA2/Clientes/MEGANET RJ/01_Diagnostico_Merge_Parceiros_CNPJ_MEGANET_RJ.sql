DECLARE
  V_DIF NUMBER;
  V_A   VARCHAR2(4000);
  V_B   VARCHAR2(4000);
  PROCEDURE DETALHA(P_A NUMBER, P_B NUMBER) IS
  BEGIN
    FOR C IN (
      SELECT COLUMN_NAME, DATA_TYPE
        FROM ALL_TAB_COLUMNS
       WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
         AND TABLE_NAME='TGFPAR'
         AND COLUMN_NAME NOT IN ('CODPARC','DTCAD','DTALTER')
         AND DATA_TYPE NOT IN ('BLOB','CLOB','NCLOB','LONG','LONG RAW','BFILE','XMLTYPE')
       ORDER BY COLUMN_ID
    ) LOOP
      EXECUTE IMMEDIATE
        'SELECT COUNT(*),MAX(TO_CHAR(A."'||C.COLUMN_NAME||'")),MAX(TO_CHAR(B."'||C.COLUMN_NAME||'")) '||
        'FROM TGFPAR A JOIN TGFPAR B ON B.CODPARC=:1 WHERE A.CODPARC=:2 '||
        'AND DECODE(A."'||C.COLUMN_NAME||'",B."'||C.COLUMN_NAME||'",0,1)=1'
        INTO V_DIF,V_A,V_B USING P_B,P_A;
      IF V_DIF>0 THEN
        DBMS_OUTPUT.PUT_LINE('PAR='||P_A||'/'||P_B||';CAMPO='||C.COLUMN_NAME||
          ';ORIGEM='||NVL(V_A,'<NULL>')||';DESTINO='||NVL(V_B,'<NULL>'));
      END IF;
    END LOOP;
  END;
BEGIN
  DETALHA(2667,1619);
  DBMS_OUTPUT.PUT_LINE('PAR=2689/481;DETALHAMENTO=NAO_APLICAVEL_FORA_DO_ESCOPO');
END;
